def 창(i, shift):
    s = (23 + 2 * i) % 24 * 60 + shift
    e = (s + 120) % 1440
    return '%02d:%02d~%02d:%02d' % (s // 60 % 24, s % 60, e // 60 % 24, e % 60)


def 짜기(월키, 시작일, 끝일, shift, 부모, 지역):
    d = json.load(io.open(os.path.join(ROOT, '.taekil', '_taekil.json'),
                          encoding='utf-8'))[월키]
    날 = [r for r in d['d'] if 시작일 <= r[0] <= 끝일]

    # 이 기간 안에서 다시 줄 세운다. 점수는 그 달 전체 기준 그대로 둔다 —
    # 다시 펴면 우리 월별 글과 숫자가 어긋난다.
    칸 = []
    for r in 날:
        for i in range(12):
            칸.append({'일': r[0], '요일': r[1], '일주': r[2], 'i': i,
                       '점': r[3 + i], '월순': r[15 + i]})
    칸.sort(key=lambda x: (-x['점'], x['일'], x['i']))
    for n, x in enumerate(칸):
        x['순'] = n + 1
    표 = {(x['일'], x['i']): x for x in 칸}

    # 부모 일지와 부딪히는 자리. 가족 정보는 **좋은 자리를 찾는 재료가 아니라
    # 나쁜 자리를 거르는 체**다(택일상담 스킬). 그래서 점수에 안 넣고 표시만 한다.
    충지 = {(지지.index(p[1]) + 6) % 12 for p in 부모}
    def 부딪(x):
        말 = []
        if 지지.index(x['일주'][1]) in 충지:
            말.append('그날 자체')
        if x['i'] in 충지:
            말.append('그 시각')
        return 말

    return 칸, 표, 부딪, 날


def 본문(칸, 표, 부딪, 날, shift, 조건, 부모, 간여):
    상위 = '<br>\n        '.join(
        '▸ <b>%d위</b> %d일(%s) %s %s · %d점%s'
        % (x['순'], x['일'], x['요일'], 시진[x['i']], 창(x['i'], shift), x['점'],
           ' <b>· 부모와 부딪힘</b>' if 부딪(x) else '')
        for x in 칸[:10])

    걸림 = [x for x in 칸 if 부딪(x)]
    걸린날 = sorted({x['일'] for x in 칸 if '그날 자체' in 부딪(x)})

    블록 = []
    for r in 날:
        줄 = ['▸ <b>%d일(%s)</b> %s' % (r[0], r[1], r[2])]
        칸들 = sorted(range(12), key=lambda i: 표[(r[0], i)]['순'])
        for i in 칸들:
            x = 표[(r[0], i)]
            본 = '%s %s · %d점 · %d위' % (시진[i], 창(i, shift), x['점'], x['순'])
            if 부딪(x):
                본 += ' · 부모와 부딪힘'
            줄.append('&nbsp;&nbsp;' + ('<b>%s</b>' % 본 if x['순'] <= 10 else 본))
        블록.append('<br>\n        '.join(줄))

    창표 = '<br>\n        '.join(
        '▸ <b>%s시</b> — 시계 %s' % (시진[i], 창(i, shift)) for i in range(12))

    return {
        '조건': 조건,
        '상위': 상위,
        '부모': ' · '.join('%s %s일주' % (n, p) for n, p in 부모.items())
                if isinstance(부모, dict) else 부모,
        '걸림수': len(걸림), '걸린날': '·'.join('%d일' % d for d in 걸린날),
        '블록': '\n\n    <hr>\n\n    '.join(
            '<blockquote>\n      <p>%s</p>\n    </blockquote>' % b for b in 블록),
        '창표': 창표, '칸수': len(칸), '보정': shift, '간여': 간여,
    }


