    const 주와앞 = (p) => { const R = En.calc(p); return { 주: B.주(R, 월), 앞체: B.변화(B.층표(R, 앞날)).체 }; };
    let 나; try { 나 = 주와앞(profile); } catch (e) { return 숨김(); }
