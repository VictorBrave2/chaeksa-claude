    const 오늘글 = 날짜글(오늘);
    const S = { 주: 나.주, 앞체: 나.앞체, 그주: 그 && 그.주, 그앞체: 그 && 그.앞체, 그사람이름: (그사람 && 그사람.name) || '', 오늘: 오늘글, 고른: 나.주.날들.some(x => x.날짜 === 오늘글) ? 오늘글 : 나.주.뾰족한날.날짜 };
