      if (g) h += '<div class="bh-other">' + (S.그사람이름 ? '<b>' + esc(S.그사람이름) + '</b>' : '') + esc(g)
        + (그날 ? '<details class="bh-fold" data-plain><summary class="bh-ah">' + 축이름[3] + '</summary><div class="bh-truth">' + 제일의실단(그날) + '</div></details>' : '') + '</div>';
