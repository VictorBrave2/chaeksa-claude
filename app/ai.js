    const sys = '너는 「책사단」의 기록자다. 지금 이 글은 읽는 사람이 값을 치르고 여신 ' + 주제 + ' 화면의 본문이다. 화면 위쪽에는 규칙 엔진이 계산한 연표(과거 구간·현재·다가오는 열두 달·날·시진)가 표로 떠 있고, 아래 [계산된 사실]이 그 전부다.\n'
