/* 관점 — 「판정엔진 + 관점 조문 = 콘텐츠」 (법전 63조, 2026-09-17 사장님)
 *
 *   판정엔진(panjeong.js 의 문 하나)  +  관점(이 파일)  =  콘텐츠(화면 · 글 · 보고서)
 *
 * 관점은 **무엇을 보고 · 무엇을 걸림이라 부르고 · 어떻게 말하나**만 적는다. 여기서 새로 재지 않는다.
 * 재는 것은 전부 판정엔진이 한다 — 이 파일은 엔진이 내준 층(표 · 격 · 조후 · 성패)을 읽기만 한다.
 * 화면(taekilsim.js 따위)은 관점이 내준 말을 그리기만 한다. 명리가 한 줄도 없어야 한다.
 *
 * 60조 — 종합 점수를 내지 않는다. 눈마다 각자 본 것을 각자의 말로. 줄은 점수가 아니라 조건(걸림 없음)으로 거른다.
 * 눈마다 믿는 해상도까지만 쓴다: 궁통보감은 120칸 표 그대로 · 자평진전은 「파격인가」까지 · 적천수는 통관(61 · 62조).
 */
(function (global) {
  'use strict';
  const E = global.ChaeksaEngine, G = global.ChaeksaSaenggeuk;
  if (!E || !G) return;

  const 받침 = (s) => { const t = String(s).replace(/\([^)]*\)\s*$/, ''); if (!t) return false; const c = t.slice(-1).charCodeAt(0); return c >= 0xAC00 && c <= 0xD7A3 && ((c - 0xAC00) % 28) !== 0; };
  const 조 = (s, 있, 없) => s + (받침(s) ? 있 : 없);
  const 이가 = (s) => 조(s, '이', '가'), 을를 = (s) => 조(s, '을', '를'), 은는 = (s) => 조(s, '은', '는');
  const 묶어 = (arr) => arr.length <= 1 ? (arr[0] || '') : 조(arr.slice(0, -1).join(', '), '과', '와') + ' ' + arr[arr.length - 1];
  const 한자간 = (ch) => { const i = E.STEMS.indexOf(ch); return i < 0 ? ch : G.이름(i); };            // 壬 → 임수(壬)
  const 성패말 = { 섰다: '성격', 구제됐다: '구응', 띠었다: '기신 있음', 깨졌다: '파격' };                  // 엔진 안쪽 키는 화면에 안 낸다
  const 달이름 = (b) => E.BRANCHES_KO[b] + '(' + E.BRANCHES[b] + ')월';

  /* ── 출산택일 관점 ──
   *  보는 층: 원국만. 대운은 유료 보고서의 몫이다(09-17 결재 4). 일간은 「아이」라고 부른다. */
  const 출산택일 = {
    이름: '출산택일',
    층: '원국',
    머리: '세 고전이 각자 본 것을 그대로 적었어요. 점수로 합치지 않습니다 — 셋은 서로 다른 것을 봐요.',
    없음말: '세 눈 모두 걸리는 것이 없어요',
    꼬리: '여기까지가 기계가 보는 것이에요. 100점짜리 원국은 있어도, 아이의 삶은 대운과 환경에 좌우돼요. 대운 · 부모님 사주와의 충 · 담당 선생님 수술 시간은 보고서에서 사람이 봅니다.',
    눈: [
      {
        key: '조후', 고전: '궁통보감', 묻는것: '이 계절에 이 아이에게 필요한 글자가 하늘에 있나',
        읽기(층, R) {
          const j = 층.조후; if (!j) return null;
          const 필요 = 한자간(j.need), 돕는 = (j.aux || '').split('').filter(Boolean).map(한자간);
          const 걸림 = !j.hasMain || j.감점 > 0;
          const 한줄 = j.hasMain ? (j.감점 > 0 ? '필요한 글자는 있는데 걸리는 구절이 있어요' : '필요한 글자가 하늘에 있어요')
            : (j.hasAux ? '필요한 글자는 없고 돕는 글자만 있어요' : '필요한 글자가 하늘에 없어요');
          const 풀이 = [
            달이름(R.pillars.month.branch) + '에 태어난 ' + G.이름(R.pillars.day.stem) + ' 아이에게 궁통보감은 ' + 을를(필요) + ' 먼저 찾아요'
              + (돕는.length ? '. 돕는 글자는 ' + 묶어(돕는) + '예요.' : '.'),
            '이 시각의 하늘 글자는 ' + (j.cheon || '').split('').map(한자간).join(' · ') + '이에요 — ' + 필요 + (j.hasMain ? '가 있어요.' : '는 없어요.')
              + (!j.hasMain && j.hasAux ? ' 돕는 글자는 있어요.' : ''),
          ];
          if (j.감점 > 0) 풀이.push(/[一-鿿]{4,}/.test(j.사유 || '') ? '원문에 걸리는 구절이 있어요: 「' + j.사유 + '」' + (j.기신글자 ? ' — 하늘에 ' + j.기신글자.split('').map(한자간).join(' · ') + '가 무리 지어 있어요.' : '')
            : '같은 기운의 글자가 하늘에 무리 지어 있어요' + (j.기신글자 ? '(' + j.기신글자.split('').map(한자간).join(' · ') + ').' : '.'));
          return { 걸림, 한줄, 풀이 };
        },
      },
      {
        key: '격', 고전: '자평진전', 묻는것: '무슨 격이고, 깨졌나',
        읽기(층) {
          const s = 층.성패; if (!s || !s.격) return { 걸림: false, 한줄: '격을 하나로 잡기 어려워요', 풀이: ['이 여덟 글자로는 격을 하나로 잡기 어려워요. 이런 자리는 사람이 봐야 해요.'], 모름: true };
          return {
            걸림: !!s.파격,
            한줄: s.격 + '격 · ' + (s.파격 ? '파격' : '파격 아님'),
            풀이: [
              '태어난 달에서 ' + s.격 + '격을 잡아요. 엔진이 본 것은 「' + (성패말[s.판정] || s.판정) + '」이에요.',
              '저희는 「깨졌나 아닌가」까지만 기계로 말해요. 성격 · 구응 · 기신 있음을 잘게 가르는 일은 글자 사이의 거리와 합을 사람이 봐야 해서 보고서에서 다시 봅니다.',
            ],
          };
        },
      },
      {
        key: '통관', 고전: '적천수', 묻는것: '아이를 치는 글자와 아이 사이가 이어져 있나',
        읽기(층) {
          const rows = (층.표.쌍 || []).filter(r => r.관계 === '극' && r.to.일간 && r.from.산다 && !r.from.운 && !r.from.지지);
          if (!rows.length) return { 걸림: false, 한줄: '아이를 치는 글자가 겉에 없어요', 풀이: ['하늘 글자 가운데 아이를 치는 글자가 없어요. 없다는 것이 좋다 나쁘다는 뜻은 아니에요 — 운에서 오면 그때 봅니다.'] };
          const 뚫린 = rows.filter(r => !r.막힘);
          const 말 = (r) => {
            const 누구 = G.이름(r.from.stem) + ' ' + r.from.십신;
            if (r.통관) return 이가(누구) + ' 아이를 치는데 ' + 이가(묶어(r.셋째.map(c => G.이름(c.stem)))) + ' 사이를 이어 줘요(통관).';
            if (r.제복) return 이가(누구) + ' 아이를 치는데 ' + 이가(묶어(r.잡는.map(c => G.이름(c.stem)))) + ' 그 글자를 잡고 있어요(제복).';
            if (r.힘차이) return 이가(누구) + ' 아이를 치려 하지만 힘이 모자라 못 쳐요.';
            const 멀리 = (r.셋째탈락 || []).filter(x => x.사유 === '떨어짐').map(x => G.이름(x.글자.stem));
            return 이가(누구) + ' 아이에게 막힘 없이 닿아요.' + (멀리.length ? ' 이어 줄 ' + 이가(묶어(멀리)) + ' 있지만 아이 옆에 붙어 있지 않아요.' : '');
          };
          return {
            걸림: 뚫린.length > 0,
            한줄: 뚫린.length ? '아이를 치는 글자가 막힘 없이 닿아요' : '아이를 치는 글자가 있지만 사이가 이어져 있어요',
            풀이: rows.map(말),
          };
        },
      },
    ],
  };

  /** 관점으로 판정 결과를 읽는다 → { 눈들: [{key, 고전, 묻는것, 걸림, 한줄, 풀이}], 걸림수, 없음 }. 점수는 없다. */
  function 읽기(관점, 판정결과, R) {
    const 층 = (판정결과.층들 || []).find(x => x.이름 === 관점.층) || (판정결과.층들 || [])[0];
    const 눈들 = 관점.눈.map(n => { let v = null; try { v = n.읽기(층, R); } catch (e) { v = null; } return Object.assign({ key: n.key, 고전: n.고전, 묻는것: n.묻는것 }, v || { 걸림: false, 한줄: '읽지 못했어요', 풀이: [], 모름: true }); });
    const 걸림수 = 눈들.filter(x => x.걸림).length;
    return { 눈들, 걸림수, 없음: 걸림수 === 0 && !눈들.some(x => x.모름) };
  }

  global.ChaeksaGwanjeom = { 출산택일, 읽기 };
})(window);
