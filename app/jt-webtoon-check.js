/* 정통사주 웹툰 원고 검사기(09-26 — 사장님 「쉬운 문장 = 사주 모르는 친구가 읽고 되묻지 않는 문장」).
 * 기계가 잡을 수 있는 것: 우리끼리 정한 비유 열쇠말 · 사주 말 · 판정키 · 금지 낱말 · 빈칸. 되묻기 자체는 검수 에이전트가.
 * JT.검사(R) → [{ 회, 칸, 종류, 말 }] — 빈 배열이면 통과. */
(function (global) {
  const J = global.ChaeksaJtWebtoon; if (!J) return;
  // 답 · 장면 · 나에서 금지하는 비유 열쇠말 — 사주 말을 바꿔 부른 것들(작가 규칙과 같은 목록)
  const 비유 = /작은 불|큰 불|촛불|땔감|도끼|앉힌|앉은 채|앉는 곳|앉는 사람|접힌|접혀|펴져|펴지는|펴 주는|기운[,. ]|기운이에요|기운을|손이 |손도 |손은 |글자|판이 |판을 |밀고 당기|미는 건|미는 게|받쳐|채워 써|채워요|빈 데|빈 쪽|나와 같은 편|내 재주|맡겨지는 일|덮어 주는|흩어 주는|실어 주는/;
  const 사주말 = /(식신|상관|편인|정인|겁재|비견|편재|정재|편관|정관)(격|이|은|을|과|와)|십신|대운|세운|원국|장생|목욕|관대|건록|제왕|천을|화개|역마|공망|양인|함지|겁살|망신|괴강|성격|파격|기신|구응|상신/;
  const 판정키 = /섰다|섰는데|띠었|온전|흠 /;
  const 금지 = /자리|잣대|표지|이레|공략|사주는|지시 |자료 |성과 |실행 |동료 /;
  function 검사(R) {
    const 걸 = [];
    (J.조립(R, {}) || []).forEach(h => h.줄.forEach(([칸, 말]) => {
      const 곳 = { 회: h.번호, 칸 };
      if (/\{|\}|쓰고 있어요|undefined|  /.test(말)) 걸.push(Object.assign({ 종류: '빈칸 · 깨진 변수', 말 }, 곳));
      if (칸 !== '답' && 칸 !== '장면' && 칸 !== '나') return;
      if (비유.test(말)) 걸.push(Object.assign({ 종류: '비유 열쇠말(되묻게 됨)', 말 }, 곳));
      if (사주말.test(말)) 걸.push(Object.assign({ 종류: '사주 말', 말 }, 곳));
      if (판정키.test(말)) 걸.push(Object.assign({ 종류: '판정키', 말 }, 곳));
      if (금지.test(말) && !(/회사 자리/.test(말) && [3, 4, 6].indexOf(h.번호) >= 0)) 걸.push(Object.assign({ 종류: '금지 낱말', 말 }, 곳));
    }));
    return 걸;
  }
  J.검사 = 검사;
})(window);
