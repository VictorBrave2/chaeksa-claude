/* 정통사주 웹툰 원고 검사기(09-26 — 사장님 「쉬운 문장 = 사주 모르는 친구가 읽고 되묻지 않는 문장」).
 * 기계가 잡을 수 있는 것: 우리끼리 정한 비유 열쇠말 · 사주 말 · 판정키 · 금지 낱말 · 빈칸. 되묻기 자체는 검수 에이전트가.
 * JT.검사(R) → [{ 회, 칸, 종류, 말 }] — 빈 배열이면 통과. */
(function (global) {
  const J = global.ChaeksaJtWebtoon; if (!J) return;
  // 답 · 장면 · 나에서 금지하는 비유 열쇠말 — 사주 말을 바꿔 부른 것들(작가 규칙과 같은 목록)
  const 비유 = /작은 불|큰 불|촛불|땔감|도끼|앉힌|앉은 채|앉는 곳|앉는 사람|접힌|접혀|펴져|펴지는|펴 주는|손이 |손도 |손은 |글자|판이 |판을 |밀고 당기|미는 건|미는 게|받쳐|채워 써|채워요|빈 데|빈 쪽|나와 같은 편|내 재주|맡겨지는 일|덮어 주는|흩어 주는|실어 주는/;
  const 사주말 = /(식신|상관|편인|정인|겁재|비견|편재|정재|편관|정관)(격|이|은|을|과|와)|십신|대운|세운|원국|장생|목욕|관대|건록|제왕|천을|화개|역마|공망|양인|함지|겁살|망신|괴강|성격|파격|기신|구응|상신/;
  const 판정키 = /섰다|섰는데|띠었|온전|흠 /;
  const 금지 = /자리|잣대|표지|이레|공략|사주는|지시 |자료 |성과 |실행 |동료 /;
  // 09-26 되묻기 검수 1바퀴에서 기계로 옮긴 것: 얼버무리는 꼬리 · 뜻 없는 말
  const 얼버무림 = /열 해|타고난 데선|데선 |오래 가요|쓰임이 바뀌|힘으로 가요|계절이 (잘|안) 맞는 편|맞는 편이라|밀어 줘요|당겨요|일 이름|파는 |여물|막아 낸 힘|앞으로도 그래요|풀리진 않아요|겨우 맞춰요|떠나면|같은 편 쪽|여기서 안 나와요|이름은 그대로|있나 없나/;   // 2바퀴 ⑦: 「파는」(팔다 오독) · 「여물」 · 결론 못 박기
  function 검사(R) {
    const 걸 = [];
    (J.조립(R, {}) || []).forEach(h => h.줄.forEach(([칸, 말]) => {
      const 곳 = { 회: h.번호, 칸 };
      if (/\{|\}|쓰고 있어요|undefined|  /.test(말)) 걸.push(Object.assign({ 종류: '빈칸 · 깨진 변수', 말 }, 곳));
      if (칸 === '해설' && /성격|기신|구응|파격|격이 |격은 |격을 /.test(말)) 걸.push(Object.assign({ 종류: '해설에 성패 넷 말(1층은 좋은/나쁜 상태)', 말 }, 곳));   // 09-26 사장님
      if (칸 !== '답' && 칸 !== '장면' && 칸 !== '나') return;
      if (비유.test(말)) 걸.push(Object.assign({ 종류: '비유 열쇠말(되묻게 됨)', 말 }, 곳));
      if (사주말.test(말)) 걸.push(Object.assign({ 종류: '사주 말', 말 }, 곳));
      if (판정키.test(말)) 걸.push(Object.assign({ 종류: '판정키', 말 }, 곳));
      if (칸 === '답' && 얼버무림.test(말)) 걸.push(Object.assign({ 종류: '얼버무림(되묻게 됨)', 말 }, 곳));
      if (칸 === '답' && h.번호 === 18 && /\d{4}년/.test(말) && !/바뀌|그대로|다른 일|이어져/.test(말)) 걸.push(Object.assign({ 종류: '18회 연도만(무엇으로 바뀌었나 없음)', 말 }, 곳));
      if (금지.test(말) && !(/회사 자리/.test(말) && [3, 4, 6].indexOf(h.번호) >= 0)) 걸.push(Object.assign({ 종류: '금지 낱말', 말 }, 곳));
    }));
    // 한 사람 안에서 「못 재요」 3회 이상 — 되묻게 됨(2바퀴 18~21)
    const 못잼 = (J.조립(R, {}) || []).reduce((n, h) => n + h.줄.filter(([k, 말]) => k === '답' && /못 재요/.test(말)).length, 0); if (못잼 >= 3) 걸.push({ 회: 0, 칸: '답', 종류: '「못 재요」 ' + 못잼 + '번', 말: '' });
    // 3바퀴: 한 사람 안에서 앞뒤가 뒤집히는 것 — 조각 고정문이 엔진 값과 어긋남
    try { const 사 = J.사람(R), 답 = {}; (J.조립(R, {}) || []).forEach(h => { const a = h.줄.find(x => x[0] === '답'); if (a) 답[h.번호] = a[1]; });
      if (사.상신말 && /끌어 준 사람 없이|혼자 힘으로/.test(답[5] || '')) 걸.push({ 회: 5, 칸: '답', 종류: '앞뒤(상신 있는데 「혼자 힘으로」)', 말: 답[5] });
      if (!사.재성있음 && /돈/.test(답[7] || '')) 걸.push({ 회: 7, 칸: '답', 종류: '앞뒤(재성 없는데 돈이 흔든다)', 말: 답[7] });
      if (사.지금대운 && /파격|기신/.test(사.지금대운.성패) && /잘 안 흔들려요|든든해요\.$/.test(답[6] || '')) 걸.push({ 회: 6, 칸: '답', 종류: '앞뒤(지금 열 해가 흔들리는데 「안 흔들려요」)', 말: 답[6] });
      if (/\d{4}년/.test(답[17] || '') && /돌아올 해도 없어요|떠난 적이 없어요/.test(답[19] || '') && 사.바뀜.length) 걸.push({ 회: 19, 칸: '답', 종류: '앞뒤(17회는 바뀐다는데 19회는 떠난 적 없다)', 말: 답[19] });
      if (사.펴짐 && 사.펴짐.시작 <= 사.올해 && /년부터 풀려요/.test((답[6] || '') + (답[20] || ''))) 걸.push({ 회: 6, 칸: '답', 종류: '앞뒤(지난 해를 앞날처럼 「풀려요」)', 말: 답[6] });
      // 4바퀴
      if (/옆 사람이 있어야/.test(답[1] || '') && /혼자일 때/.test(답[16] || '')) 걸.push({ 회: 16, 칸: '답', 종류: '앞뒤(1회 옆 사람 ↔ 16회 혼자)', 말: 답[16] });
      if (사.바뀜.length && 사.바뀜[0].시작 <= 사.올해 && /년이에요|년부터 (돈 쓰는 데가 )?달라져요/.test((답[12] || '') + (답[17] || '')) && !/이미/.test((답[12] || '') + (답[17] || ''))) 걸.push({ 회: 17, 칸: '답', 종류: '앞뒤(지난 바뀐 해를 앞날처럼)', 말: 답[17] || 답[12] });
      if (사.돌아옴잘림 && /안 돌아와요/.test(답[19] || '')) 걸.push({ 회: 19, 칸: '답', 종류: '앞뒤(원격 대운이 있는데 「안 돌아와요」)', 말: 답[19] });
      if (사.성패 !== '성격' && 사.성패 !== '구응' && !사.구응 && /붙잡아 주는|막아 주는 것도/.test(답[7] || '')) 걸.push({ 회: 7, 칸: '답', 종류: '앞뒤(구응 없는데 붙잡아 준다)', 말: 답[7] });
    } catch (e) {}
    return 걸;
  }
  J.검사 = 검사;
})(window);
