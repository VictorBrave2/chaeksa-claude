  function applyModel(model) {
    if (!model || typeof model !== 'object') return model;
    const copy = fields(model, ['dateNote']);
    copy.identity = fields(model.identity, ['title', 'line', 'basis']);
    copy.lens = fields(model.lens, ['title', 'tag', 'line', 'have', 'shortNeed', 'event', 'explanation', 'note', 'limits', 'source']);
    if (copy.lens) {
      copy.lens.checks = (model.lens.checks || []).map(c => fields(c, ['title', 'detail']));
      if (model.lens.experience) copy.lens.experience = fields(model.lens.experience, ['title', 'emphasis', 'thought', 'action', 'summary', 'basis']);
    }
    ['years', 'months', 'days', 'hours', 'periods'].forEach(key => {
      if (Array.isArray(model[key])) copy[key] = model[key].map(item => fields(item, ['name', 'line', 'boundary']));
    });
    if (model.filterStory) {
      copy.filterStory = { ...model.filterStory };
      if (Array.isArray(model.filterStory.filters)) copy.filterStory.filters = model.filterStory.filters.map(f => baseFilterCopy(root.ChaeksaJeongtongClassicReading?.mapFilter ? root.ChaeksaJeongtongClassicReading.mapFilter(f) : f));
    }
    return copy;
  }
