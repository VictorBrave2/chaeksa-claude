/* 책사 협기층 — 《欽定協紀辨方書》 사고전서본의 날 신살
 *
 * 판본·원문 인용·검증 노트: docs/20_협기변방서.md (2026-08-30 채록)
 * 자평진전·궁통보감과 같은 절차로 원문을 채록해 만들었다. 기억으로 쓴 표가 아니다.
 *
 * 우리 본축(원국 맞춤 — 조후·통근)과 축이 다르다. 협기는 만인 공통의 날 신살이라
 * **보조 축**이다: 「민력이 길일이라 한 날이 당신 사주엔 아닌 이유」의 대조가 값이다.
 *
 * 자기검증 불변식 셋 (원문 교차 검증에서 나온 것 — selfCheck()):
 *   ① 천덕합 = 合(천덕)  ② 월공 = 월덕의 충 천간  ③ 월파일 = 건제 破日
 */
(function (global) {
  'use strict';
  const E = global.ChaeksaEngine;

  // ── 건제십이신 (권4) — 신 = (일지 − 월건) mod 12 ──
  const 건제이름 = ['建', '除', '滿', '平', '定', '執', '破', '危', '成', '收', '開', '閉'];
  const 건제한글 = ['건', '제', '만', '평', '정', '집', '파', '위', '성', '수', '개', '폐'];
  // 宜 — 권10 원문의 현대어 요약 (원문은 docs/20)
  const 건제의 = [
    '취임·발령·공식 자리에 서는 일',
    '청소·목욕·이발·치료 시작 — 묵은 것을 터는 일',
    '개업·계약·돈 들이기·사람 들이기',
    '정리·정비 — 길 닦고 고르는 일',
    '예식 — 자리를 정하는 일',
    '붙잡는 일 — 계약 체결·마감',
    '치료와 철거에만 좋다 — 그 외는 벌이지 말 것',
    '자리 놓기(안상) — 조심스럽게 움직이는 날',
    '입학·이사·개업 — 이루어지는 날',
    '거두는 일 — 수금·입고',
    '여는 일 전반 — 제사·기복·개업 (다만 안장·벌목은 꺼림)',
    '막고 메우는 일 — 마감·봉인',
  ];

  // ── 천덕·월덕 계열 (권5) — 명리월 1=寅월 기준 ──
  // 2·5·8·11월 천덕은 방위(坤乾艮巽)라 날로는 못 쓴다 → null (원문 그대로 기록)
  const 천덕 = [3, null, 8, 7, null, 0, 9, null, 2, 1, null, 6];       // 丁·坤·壬·辛·乾·甲·癸·艮·丙·乙·巽·庚
  const 천덕합 = 천덕.map(s => (s == null ? null : (s + 5) % 10));      // 불변식 ① 정의 자체가 검증
  const 월덕그룹 = [2, 0, 8, 6];                                        // 寅午戌→丙 · 亥卯未→甲 · 申子辰→壬 · 巳酉丑→庚
  // 삼합군을 시작 지지로 편다: 寅午戌(화)→丙 · 亥卯未(목)→甲 · 申子辰(수)→壬 · 巳酉丑(금)→庚
  const 월덕 = (월건) => 월덕그룹[[2, 11, 8, 5].map(w => [w, (w + 4) % 12, (w + 8) % 12]).findIndex(g => g.indexOf(월건) >= 0)];
  const 월덕합 = (월건) => (월덕(월건) + 5) % 10;
  // 월공 = 월덕의 충 천간 짝: 丙↔壬 · 甲↔庚 (원문 표와 전 칸 일치)
  const 충간 = { 2: 8, 8: 2, 0: 6, 6: 0 };
  const 월공 = (월건) => 충간[월덕(월건)];

  /** 그 날의 협기 신살. tf = ChaeksaEngine.dateFortune(y,m,d) */
  function 날신살(tf) {
    const 월건 = tf.month.branch, 일지 = tf.day.branch, 일간 = tf.day.stem;
    const k = (일지 - 월건 + 12) % 12;
    const out = {
      건제: { 한자: 건제이름[k], 이름: 건제한글[k] + '일(' + 건제이름[k] + ')', 의: 건제의[k], 파: k === 6 },
      길신: [],
    };
    const 월번호 = (월건 - 2 + 12) % 12;      // 0 = 정월(寅)
    if (천덕[월번호] === 일간) out.길신.push('천덕');
    if (천덕합[월번호] === 일간) out.길신.push('천덕합');
    if (월덕(월건) === 일간) out.길신.push('월덕');
    if (월덕합(월건) === 일간) out.길신.push('월덕합');
    if (월공(월건) === 일간) out.길신.push('월공');
    return out;
  }

  // ── 2차 채록 (권5·6·11) — docs/20 에 원문. 위키 변환 오류 巳→己 는 합짝·표 논리로 교정 ──
  // 계절 = 월지: 寅卯辰 봄 · 巳午未 여름 · 申酉戌 가을 · 亥子丑 겨울
  const 계절 = (월건) => [3, 3, 0, 0, 0, 1, 1, 1, 2, 2, 2, 3][월건];
  // 天赦: 春戊寅 夏甲午 秋戊申 冬甲子
  const 천사표 = [[4, 2], [0, 6], [4, 8], [0, 0]];
  // 母倉: 春亥子 夏寅卯 秋辰戌丑未 冬申酉 (土王後 규칙은 미구현 — docs/20 명시)
  const 모창표 = [[11, 0], [2, 3], [4, 10, 1, 7], [8, 9]];
  // 四相: 春丙丁 夏戊己 秋壬癸 冬甲乙
  const 사상표 = [[2, 3], [4, 5], [8, 9], [0, 1]];
  // 時德: 春午 夏辰 秋子 冬寅
  const 시덕표 = [6, 4, 0, 2];
  // 月恩 (월별 천간): 正丙 二丁 三庚 四己 五戊 六辛 七壬 八癸 九庚 十乙 十一甲 十二辛
  const 월은표 = [2, 3, 6, 5, 4, 7, 8, 9, 6, 1, 0, 7];
  // 天恩: 甲子~戊辰 · 己卯~癸未 · 己酉~癸丑 (갑자 번호 0~4 · 15~19 · 45~49)
  const 천은인가 = (i) => (i >= 0 && i <= 4) || (i >= 15 && i <= 19) || (i >= 45 && i <= 49);
  const 갑자번호 = (st, br) => { for (let i = 0; i < 60; i++) if (i % 10 === st && i % 12 === br) return i; return -1; };
  // 흉살 — 전부 원문 생성 공식:
  // 劫煞 正月起亥 逆行四孟 · (災煞 = 그 다음 사중) · 月煞 正月起丑 逆行四季
  const 겁살 = (월건) => [11, 8, 5, 2][(월건 - 2 + 12) % 4];
  const 재살 = (월건) => (겁살(월건) + 1) % 12;
  const 월살 = (월건) => (겁살(월건) + 2) % 12;
  // 大時 正月起卯 逆行四仲 · 天吏 正月起酉 逆行四仲
  const 대시 = (월건) => [3, 0, 9, 6][(월건 - 2 + 12) % 4];
  const 천리 = (월건) => [9, 6, 3, 0][(월건 - 2 + 12) % 4];
  // 月害 正月起巳 逆行十二辰 — 불변식: 월해 = 충(육합(월건))
  const 월해 = (월건) => (5 - ((월건 - 2 + 12) % 12) + 12) % 12;
  // 往亡 (월별 지지 표)
  const 왕망표 = [2, 5, 8, 11, 3, 6, 9, 0, 4, 7, 10, 1];

  function 날신살2(tf) {
    const out = 날신살(tf);
    const 월건 = tf.month.branch, 일지 = tf.day.branch, 일간 = tf.day.stem;
    const 철 = 계절(월건), 월번호 = (월건 - 2 + 12) % 12;
    const [사간, 사지] = 천사표[철];
    if (일간 === 사간 && 일지 === 사지) out.길신.push('천사');
    if (모창표[철].indexOf(일지) >= 0) out.길신.push('모창');
    if (사상표[철].indexOf(일간) >= 0) out.길신.push('사상');
    if (시덕표[철] === 일지) out.길신.push('시덕');
    if (월은표[월번호] === 일간) out.길신.push('월은');
    if (천은인가(갑자번호(일간, 일지))) out.길신.push('천은');
    out.흉신 = [];
    if (out.건제.파) out.흉신.push('월파');
    if (겁살(월건) === 일지) out.흉신.push('겁살');
    if (재살(월건) === 일지) out.흉신.push('재살');
    if (월살(월건) === 일지) out.흉신.push('월살');
    if (대시(월건) === 일지) out.흉신.push('대시');
    if (천리(월건) === 일지) out.흉신.push('천리');
    if (월해(월건) === 일지) out.흉신.push('월해');
    if (왕망표[월번호] === 일지) out.흉신.push('왕망');
    return out;
  }

  // ── 용사판 (권11 用事) — 구현된 신살만 검사한다. 미구현 목록은 docs/20 ──
  // 月刑은 「형은 안 본다」 동결 원칙(법전 제6조)에 따라 채택하지 않았다.
  const 덕신 = ['천덕', '월덕', '천덕합', '월덕합'];
  const 용사표 = {
    혼인: { 의신: 덕신.concat(['천사']), 의건제: [], 기신: ['월파', '겁살', '재살', '월살', '월해', '대시', '천리', '왕망'], 기건제: ['平', '收', '閉'] },
    이사: { 의신: 덕신.concat(['천사', '월은', '사상', '시덕']), 의건제: ['成', '開'], 기신: ['월파', '겁살', '재살', '월살', '대시', '천리', '왕망'], 기건제: ['平', '收', '閉'] },
    개업: { 의신: [], 의건제: ['滿', '成', '開'], 기신: ['월파', '겁살', '재살', '월살', '월해', '대시', '천리'], 기건제: ['平', '收', '閉'] },
    출행: { 의신: 덕신.concat(['천사', '월은', '사상', '시덕']), 의건제: ['建', '開'], 기신: ['월파', '겁살', '재살', '월살', '대시', '천리', '왕망'], 기건제: ['平', '收', '閉'] },
    부임: { 의신: 덕신.concat(['천사', '월은', '사상', '시덕']), 의건제: ['建', '開'], 기신: ['월파', '겁살', '재살', '월살', '대시', '천리', '왕망'], 기건제: ['平', '收', '滿', '閉'] },
    안장: { 의신: 덕신.concat(['천사']), 의건제: [], 기신: ['월파', '겁살', '재살', '월살', '월해'], 기건제: ['建', '平', '收'] },
    공사: { 의신: 덕신.concat(['천사', '월은', '사상', '시덕']), 의건제: ['開'], 기신: ['월파', '겁살', '재살', '월살', '대시', '천리'], 기건제: ['建', '平', '收', '閉'] },
    재종: { 의신: 덕신.concat(['천사', '모창', '월은', '사상', '시덕']), 의건제: ['開'], 기신: ['월파', '겁살', '재살', '월살'], 기건제: ['建'] },
  };
  function 용사판(tf, 용사) {
    const 표 = 용사표[용사]; if (!표) return null;
    const n = 날신살2(tf);
    const 모든 = n.길신;
    return {
      길: 모든.filter(x => 표.의신.indexOf(x) >= 0).concat(표.의건제.indexOf(n.건제.한자) >= 0 ? [n.건제.이름] : []),
      흉: n.흉신.filter(x => 표.기신.indexOf(x) >= 0).concat(표.기건제.indexOf(n.건제.한자) >= 0 ? [n.건제.이름 + ' 꺼림'] : []),
      건제: n.건제,
    };
  }

  function 날신살YMD(y, m, d) { return 날신살2(E.dateFortune(y, m, d)); }

  /** 불변식 자기검증 — 하나라도 어긋나면 표가 오염된 것이다 */
  function selfCheck() {
    const bad = [];
    // ① 천덕합 = 合(천덕) — 정의상 참이지만 표를 손대면 깨진다
    천덕.forEach((s, i) => { if (s != null && (s + 천덕합[i]) % 10 !== 5 && (천덕합[i] + s) % 10 !== 5) {
      if ((Math.abs(s - 천덕합[i]) % 10) !== 5) bad.push('천덕합 ' + (i + 1) + '월'); } });
    // ② 12월건 전부에서 월덕이 정의되고 원문 표와 일치 + 월공 = 충 천간
    const 원문 = { 2: 2, 6: 2, 10: 2, 11: 0, 3: 0, 7: 0, 8: 8, 0: 8, 4: 8, 5: 6, 9: 6, 1: 6 };
    for (let b = 0; b < 12; b++) {
      const d = 월덕(b);
      if (d === undefined) { bad.push('월덕 미정의 ' + b); continue; }
      if (d !== 원문[b]) bad.push('월덕 불일치 ' + b);
      const 공 = 월공(b);
      if ((d === 2 && 공 !== 8) || (d === 8 && 공 !== 2) || (d === 0 && 공 !== 6) || (d === 6 && 공 !== 0)) bad.push('월공 ' + b);
    }
    // ③ 월파일 = 건제 破日 — 아무 달이나 하나 표본
    const 월건 = 2, 파일지 = (월건 + 6) % 12;
    if ((파일지 - 월건 + 12) % 12 !== 6) bad.push('월파≠破');
    // ④ 겁살 공식 = 삼합군 전개 (寅午戌월亥 · 亥卯未월申 · 申子辰월巳 · 巳酉丑월寅)
    const 겁원문 = { 2: 11, 6: 11, 10: 11, 11: 8, 3: 8, 7: 8, 8: 5, 0: 5, 4: 5, 5: 2, 9: 2, 1: 2 };
    for (let b = 0; b < 12; b++) if (겁살(b) !== 겁원문[b]) bad.push('겁살 ' + b);
    // ⑤ 월해 = 충(육합(월건)) — 육해의 정의
    const YH = { 0: 1, 1: 0, 2: 11, 11: 2, 3: 10, 10: 3, 4: 9, 9: 4, 5: 8, 8: 5, 6: 7, 7: 6 };
    for (let b = 0; b < 12; b++) if (월해(b) !== (YH[b] + 6) % 12) bad.push('월해 ' + b);
    // ⑥ 왕망 표 12칸
    if (왕망표.length !== 12 || new Set(왕망표).size !== 12) bad.push('왕망');
    return bad.length ? '오염: ' + bad.join(', ') : 'ok';
  }

  global.ChaeksaHyeopgi = { 날신살: 날신살2, 날신살YMD, 용사판, selfCheck, 건제이름, 건제의, 용사목록: Object.keys(용사표) };
})(window);
