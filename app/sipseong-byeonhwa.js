/* 십성 변화 엔진 — docs/96 · 사장님 09-27 「십성 변화로 추론」.
 * 층(원국 → 대운 → 세운 → 월운 → 일운)마다 운의 천간 십성 · 지지 본기 십성이 무엇에서 무엇으로 바뀌었나만 센다.
 * 내는 것은 셋 — 이어짐(층 수 · 정편 바뀜) · 새로 옴(처음 / 다시 옴) · 빠짐(끊긴 무리 · 십성들 · 층 수) — 와 셈(처음 수 · 새로 온 수 · 변동폭)뿐.
 * 사람 말은 대응표(sipseong.js 뜻) 원문 그대로. 새로 온 십성은 중심 · 두드러짐 · 부딪힘 셋을 다 내고(고르지 않는다), 이어지던 것은 중심.
 * 체 = 원국 + 대운 + 세운 + 월운(바탕) · 용 = 일운(그날의 쓰임). 천간으로 온 것은 생각(깨달음), 지지로 온 것은 몸(행동).
 * 판정엔진과 따로 선다. 읽는 것은 engine.js 의 calc · dateFortune · currentDaeun · tenGod · HIDDEN · TEN_GODS · STEMS · BRANCHES 와 sipseong.js 의 뜻뿐.
 * 글자끼리의 관계 · 세기 · 판정 · 지장간 중기와 여기 · 기둥 위치는 보지 않는다. 결과를 단정하는 말은 없다. 상수 · 가중치 없음. */
(function (global) {
  'use strict';
  const E = global.ChaeksaEngine;
  const STEMS = E.STEMS, BRANCHES = E.BRANCHES, HIDDEN = E.HIDDEN, TEN_GODS = E.TEN_GODS;
  // 무리 다섯 = TEN_GODS 번호 ÷ 2 의 몫(docs/96 규칙 5)
  const 무리이름 = ['비겁', '식상', '재성', '관성', '인성'];
  const 쪽이름 = { 천간: '생각', 지지: '몸' };
  const 요일이름 = ['일', '월', '화', '수', '목', '금', '토'];
  const 두자리 = (n) => (n < 10 ? '0' : '') + n;
  const 날짜글 = (d) => d.getFullYear() + '-' + 두자리(d.getMonth() + 1) + '-' + 두자리(d.getDate());
  const 고유 = (arr) => arr.filter((x, i) => arr.indexOf(x) === i);

  function 십신칸(일간, st) {
    const n = E.tenGod(일간, st);
    return { 십신: TEN_GODS[n], 무리: 무리이름[Math.floor(n / 2)] };
  }
  function 천간칸(일간, st) { return Object.assign({ 글자: STEMS[st] }, 십신칸(일간, st)); }
  function 지지칸(일간, br) {
    const 본 = HIDDEN[br][0];
    return Object.assign({ 글자: BRANCHES[br], 본기: STEMS[본] }, 십신칸(일간, 본));
  }

  // 층표(R, date) — 원국(천간 셋 · 지지 본기 넷, 일간 뺌)과 운 네 층(대운 · 세운 · 월운 · 일운)의 글자 · 십신 · 무리
  function 층표(R, date) {
    const P = R.pillars, ds = P.day.stem;
    const 원국 = {
      천간: ['year', 'month', 'hour'].filter(k => P[k]).map(k => 천간칸(ds, P[k].stem)),
      지지: ['year', 'month', 'day', 'hour'].filter(k => P[k]).map(k => 지지칸(ds, P[k].branch)),
    };
    const F = E.dateFortune(date.getFullYear(), date.getMonth() + 1, date.getDate());
    const du = E.currentDaeun(R, date);
    const 층 = [];
    const 넣기 = (이름, p) => 층.push({ 이름, 간지: STEMS[p.stem] + BRANCHES[p.branch], 천간: 천간칸(ds, p.stem), 지지: 지지칸(ds, p.branch) });
    if (du) 넣기('대운', du);
    넣기('세운', F.year);
    넣기('월운', F.month);
    넣기('일운', F.day);
    return { 날짜: 날짜글(date), 요일: 요일이름[date.getDay()], 일간: STEMS[ds], 원국, 층, 대운없음: !du };
  }

  // 원국 대비 — 표시만: 같은 십신이 원국 겉(천간) · 속(지지 본기) · 없음 어디에 있나, 같은 무리의 다른 십신은 어디에 있나
  function 원국대비(원국, 십, 무) {
    const 겉 = 원국.천간.filter(c => c.십신 === 십).map(c => c.글자);
    const 속 = 원국.지지.filter(c => c.십신 === 십).map(c => c.글자);
    const 같은무리 = []
      .concat(원국.천간.filter(c => c.무리 === 무 && c.십신 !== 십).map(c => ({ 십신: c.십신, 위치: '겉', 글자: c.글자 })))
      .concat(원국.지지.filter(c => c.무리 === 무 && c.십신 !== 십).map(c => ({ 십신: c.십신, 위치: '속', 글자: c.글자 })));
    return { 위치: 겉.length ? '겉' : (속.length ? '속' : '없음'), 겉, 속, 같은무리 };
  }

  // 줄 하나(천간 줄 또는 지지 줄)를 운 층 차례로 걸으며 이어짐 · 새로 옴 · 빠짐을 센다(docs/96 규칙 6 · 7 · 8)
  // 첫 운 층의 위는 원국 같은 줄. 원국은 층 수에 안 센다. 다시 옴은 위 운 층에 있던 무리만(원국은 운 층이 아니다).
  function 줄변화(원국, 층, 줄) {
    const 원국줄 = 원국[줄], 원국무리 = 원국줄.map(c => c.무리), 원국십신 = 원국줄.map(c => c.십신);
    const 지난무리 = [];
    let 달림 = null;
    return 층.map(c => {
      const k = c[줄], 십 = k.십신, 무 = k.무리;
      let r;
      if (!달림) {
        if (원국무리.indexOf(무) >= 0) r = { 상태: '이어짐', 층수: 1, 정편바뀜: 원국십신.indexOf(십) < 0, 처음: false, 다시옴: false, 빠짐: null };
        else r = { 상태: '새로 옴', 층수: 1, 정편바뀜: false, 처음: true, 다시옴: false, 빠짐: null };
        달림 = { 무리: 무, 십성들: [{ 십신: 십, 층: c.이름 }], 층수: 1 };
      } else if (달림.무리 === 무) {
        const 앞 = 달림.십성들[달림.십성들.length - 1].십신;
        달림.십성들.push({ 십신: 십, 층: c.이름 });
        달림.층수 += 1;
        r = { 상태: '이어짐', 층수: 달림.층수, 정편바뀜: 앞 !== 십, 처음: false, 다시옴: false, 빠짐: null };
      } else {
        const 다시 = 지난무리.indexOf(무) >= 0;
        r = { 상태: '새로 옴', 층수: 1, 정편바뀜: false, 처음: !다시, 다시옴: 다시, 빠짐: { 무리: 달림.무리, 십성들: 달림.십성들.slice(), 층수: 달림.층수 } };
        달림 = { 무리: 무, 십성들: [{ 십신: 십, 층: c.이름 }], 층수: 1 };
      }
      지난무리.push(무);
      const 대비 = 원국대비(원국, 십, 무);
      return Object.assign(r, { 층: c.이름, 글자: k.글자, 본기: k.본기 || null, 십신: 십, 무리: 무, 십성들: 달림.십성들.slice(), 원국대비: 대비.위치, 원국대비상세: 대비 });
    });
  }

  // 변화(층표) — 층마다 천간 줄 · 지지 줄의 변화 + 체(원국~월운) · 용(일운) · 변동폭(셈) · 표시
  function 변화(T) {
    const 천 = 줄변화(T.원국, T.층, '천간'), 지 = 줄변화(T.원국, T.층, '지지');
    const 층 = T.층.map((c, i) => ({ 이름: c.이름, 간지: c.간지, 천간: 천[i], 지지: 지[i] }));
    const 일 = 층[층.length - 1], 월 = 층[층.length - 2];
    const 줄요약 = (e) => ({ 무리: e.무리, 십성들: e.십성들, 층수: e.층수, 상태: e.상태 });
    const 간지 = {};
    층.forEach(c => { 간지[c.이름] = c.간지; });
    const 체 = {
      간지: { 대운: 간지.대운 || null, 세운: 간지.세운, 월운: 간지.월운 },
      원국: { 천간: T.원국.천간.map(c => c.십신), 지지: T.원국.지지.map(c => c.십신) },
      천간: 줄요약(월.천간),
      지지: 줄요약(월.지지),
      층: 층.slice(0, -1),
    };
    // 변동폭 = 끊긴 이어짐 층 수(천간 + 지지) + 처음 수. 셈뿐(사장님 09-27 결정 2)
    const 처음수 = (일.천간.처음 ? 1 : 0) + (일.지지.처음 ? 1 : 0);
    const 다시옴수 = (일.천간.다시옴 ? 1 : 0) + (일.지지.다시옴 ? 1 : 0);
    const 끊긴층수 = (일.천간.빠짐 ? 일.천간.빠짐.층수 : 0) + (일.지지.빠짐 ? 일.지지.빠짐.층수 : 0);
    const 변동폭 = 끊긴층수 + 처음수;
    const 용 = { 간지: 일.간지, 천간: 일.천간, 지지: 일.지지, 처음수, 다시옴수, 새로온수: 처음수 + 다시옴수, 끊긴층수, 변동폭 };
    const 표시 = { 월운과같은간지: 일.간지 === 월.간지, 같은무리: 일.천간.무리 === 일.지지.무리, 대운없음: !!T.대운없음 };
    return { 날짜: T.날짜, 요일: T.요일, 일간: T.일간, 원국: T.원국, 층, 체, 용, 처음수, 다시옴수, 새로온수: 처음수 + 다시옴수, 끊긴층수, 변동폭, 표시 };
  }

  // 말(변화) — 대응표 원문만 붙인다. 문장 조립은 하지 않는다(작가 → 검수).
  // 새로 온 십성 = 중심 · 두드러짐 · 부딪힘 셋 다(사장님 09-27 결정 4) · 이어지던 것 = 중심(정 · 편이 섞였으면 둘 다)
  function 뜻of(십) {
    const t = ((global.ChaeksaSipseong || {}).뜻 || {})[십];
    return t ? { 중심: t.중심, 두드러짐: t.두드러짐, 부딪힘: t.부딪힘 } : null;
  }
  const 중심들 = (십성들) => 고유(십성들.map(x => x.십신)).map(s => ({ 십신: s, 중심: (뜻of(s) || {}).중심 }));
  function 줄말(줄, e) {
    const base = { 줄, 쪽: 쪽이름[줄], 층: e.층, 글자: e.글자, 십신: e.십신, 무리: e.무리, 상태: e.상태, 원국대비: e.원국대비 };
    if (e.상태 === '이어짐') return Object.assign(base, { 칸: ['중심'], 층수: e.층수, 정편바뀜: e.정편바뀜, 말: 중심들(e.십성들) });
    return Object.assign(base, {
      칸: ['중심', '두드러짐', '부딪힘'], 처음: e.처음, 다시옴: e.다시옴, 뜻: 뜻of(e.십신),
      이어지던: e.빠짐 ? { 무리: e.빠짐.무리, 층수: e.빠짐.층수, 칸: ['중심'], 말: 중심들(e.빠짐.십성들) } : null,
    });
  }
  const 체줄말 = (줄, s) => ({ 줄, 쪽: 쪽이름[줄], 무리: s.무리, 층수: s.층수, 십성들: s.십성들, 칸: ['중심'], 말: 중심들(s.십성들) });
  function 말(V) {
    return {
      날짜: V.날짜, 요일: V.요일,
      체: { 간지: V.체.간지, 천간: 체줄말('천간', V.체.천간), 지지: 체줄말('지지', V.체.지지) },
      용: { 간지: V.용.간지, 천간: 줄말('천간', V.용.천간), 지지: 줄말('지지', V.용.지지), 처음수: V.용.처음수, 새로온수: V.용.새로온수, 변동폭: V.용.변동폭 },
      층: V.층.map(c => ({ 이름: c.이름, 간지: c.간지, 천간: 줄말('천간', c.천간), 지지: 줄말('지지', c.지지) })),
      표시: V.표시,
    };
  }

  // 주(R, date) — date 부터 일곱 날. 뾰족한 날 = 변동폭 최대, 같으면 앞 날. 체는 첫날 것 한 벌, 달이 바뀌면 체바뀜에 표시.
  function 주(R, date) {
    const 날들 = [];
    for (let i = 0; i < 7; i++) {
      const d = new Date(date.getFullYear(), date.getMonth(), date.getDate() + i);
      const T = 층표(R, d), V = 변화(T);
      날들.push({ 날짜: V.날짜, 요일: V.요일, 간지: V.용.간지, 처음수: V.처음수, 다시옴수: V.다시옴수, 새로온수: V.새로온수, 끊긴층수: V.끊긴층수, 변동폭: V.변동폭, 표시: V.표시, 층표: T, 변화: V, 말: 말(V) });
    }
    let best = 0;
    날들.forEach((x, i) => { if (x.변동폭 > 날들[best].변동폭) best = i; });
    const 줄띠 = (e) => ({ 십신: e.십신, 상태: e.상태, 층수: e.층수, 처음: e.처음, 다시옴: e.다시옴 });
    const 띠 = 날들.map(x => ({ 날짜: x.날짜, 요일: x.요일, 간지: x.간지, 천간: 줄띠(x.변화.용.천간), 지지: 줄띠(x.변화.용.지지), 처음수: x.처음수, 다시옴수: x.다시옴수, 변동폭: x.변동폭, 요즘그대로: x.새로온수 === 0 }));
    const 체바뀜 = 날들.filter((x, i) => i > 0 && x.변화.체.간지.월운 !== 날들[i - 1].변화.체.간지.월운).map(x => ({ 날짜: x.날짜, 체: x.변화.체 }));
    return {
      시작: 날들[0].날짜, 끝: 날들[6].날짜, 날들, 띠,
      뾰족한날: { 차례: best + 1, 날짜: 날들[best].날짜, 요일: 날들[best].요일, 간지: 날들[best].간지, 변동폭: 날들[best].변동폭 },
      // 변동폭이 같은 날들 — 고르지 않고 다 낸다(사장님 09-27 「고르지 말고 모든 관점에서 말해 주면 이용자가 골라서 보게 될 것」). 화면은 이 날들을 나란히 보인다
      동점날들: 날들.filter(x => x.변동폭 === 날들[best].변동폭).map(x => ({ 날짜: x.날짜, 요일: x.요일, 간지: x.간지 })),
      체: 날들[0].변화.체, 체바뀜: 체바뀜.length ? 체바뀜 : null,
      요즘그대로인주: 날들.every(x => x.새로온수 === 0),
    };
  }

  global.ChaeksaByeonhwa = { 층표, 변화, 말, 주, 무리이름 };
})(typeof window !== 'undefined' ? window : globalThis);
