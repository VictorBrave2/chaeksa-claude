    const 짝날 = 그십신 === 배우자성;
    // 둘을 합친다 — 하나라도 조심이면 조심, 둘 다 좋음이면 3, 하나만 좋음이면 2, 나머지 보통.
    const a = 칸점[나.칸], b = 칸점[그.칸];
