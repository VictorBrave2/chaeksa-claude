  /** 하루 — 점수는 calendar.js 가 낸다. 말은 십신과 그 사람 자리(일지)와의 관계로 고른다. */
  function 하루(R, story, d) {
    const C = global.ChaeksaCalendar, E = global.ChaeksaEngine;
    if (!C || !E || !R) return null;
    const r = C.scoreDay(R, d.getFullYear(), d.getMonth() + 1, d.getDate(), story.기준);
    const 여명 = ((R.input && R.input.gender) || 'M') !== 'M';
    const 배우자성 = 여명 ? '정관' : '정재';
    const 등급 = r.grade;   // 3 아주 좋음 · 2 좋음 · 1 보통 · 0 피하기
    // 말은 점수와 같은 방향이어야 한다. 「보통이에요」 옆에 「붙는 날이에요, 연락하면 받아요」가 서면 어느 쪽이 맞는지 모른다.
    // 합·충 말은 점수가 그쪽으로 갔을 때만 쓰고, 아니면 그날 십신 말로 간다.
    let 말 = '';
    if (등급 >= 2 && (r.rel === '합' || r.rel === '삼합')) 말 = story.붙음;
    else if (등급 === 0 && r.rel === '충') 말 = story.어긋남;
    else if (r.god === 배우자성 && story.짝말) 말 = story.짝말;
    else 말 = story.말[r.god] || '';
    const 표 = 등급 >= 2 ? '○' : 등급 === 1 ? '△' : '✕';
    const 한마디 = 등급 >= 2 ? story.좋음 : 등급 === 1 ? story.보통 : story.조심;
    return { d, 요일: 요일[d.getDay()], 날: d.getDate(), 등급, 표, 한마디, 말, 점수: r.score, 십신: r.god, 관계: r.rel };
  }

  /** 오늘부터 7일 — 무료 */
  function 일주일(R, story, from) {
    const out = [];
    for (let i = 0; i < 7; i++) {
      const d = new Date(from.getFullYear(), from.getMonth(), from.getDate() + i);
      const x = 하루(R, story, d); if (x) out.push(x);
    }
    return out;
  }

  /** 이번 달 — 유료. 오늘부터 말일까지(지난 날은 안 판다). */
  function 이번달(R, story, from) {
    const y = from.getFullYear(), m = from.getMonth();
    const 말일 = new Date(y, m + 1, 0).getDate();
    const out = [];
    for (let d = from.getDate(); d <= 말일; d++) {
      const x = 하루(R, story, new Date(y, m, d)); if (x) out.push(x);
    }
    return out;
  }

