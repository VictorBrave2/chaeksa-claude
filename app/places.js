/* 책사 출생지 — 진태양시 보정과 표준시 판정에 쓴다.
 *
 * 왜 필요한가
 *  - 진태양시는 경도로 정해진다. 서울(126.98°)과 부산(129.08°)은 8분 넘게 차이가 나고,
 *    이 차이가 시주(時柱)의 경계를 넘길 수 있다.
 *  - 해외 출생이면 표준시 자체가 다르다. 한국 시간으로 계산하면 원국이 통째로 틀린다.
 *
 * 한계(정직하게)
 *  - 해외 도시의 과거 서머타임은 반영하지 않는다. 해당 시기에 서머타임이 있었다면
 *    태어난 시각에서 1시간을 빼고 입력해야 한다. 화면에도 이 안내를 띄운다.
 *  - 한국의 역사적 표준시 변경(1954~1961 UTC+8:30)과 1987~88 서머타임은 엔진이 자동 처리한다.
 */
(function (global) {
  'use strict';

  const KOREA = [
    ['서울', 126.98], ['인천', 126.70], ['수원', 127.03], ['성남', 127.13],
    ['춘천', 127.73], ['강릉', 128.90], ['원주', 127.95],
    ['대전', 127.38], ['세종', 127.29], ['청주', 127.49], ['천안', 127.15],
    ['전주', 127.15], ['광주', 126.85], ['목포', 126.39], ['여수', 127.66],
    ['대구', 128.60], ['안동', 128.73], ['포항', 129.36],
    ['부산', 129.08], ['울산', 129.31], ['창원', 128.68], ['진주', 128.11],
    ['제주', 126.53], ['서귀포', 126.56],
  ];

  // [이름, 표준시 오프셋(시간), 경도]
  const ABROAD = [
    ['도쿄', 9, 139.69], ['오사카', 9, 135.50],
    ['베이징', 8, 116.41], ['상하이', 8, 121.47], ['홍콩', 8, 114.17], ['타이베이', 8, 121.56],
    ['싱가포르', 8, 103.82], ['마닐라', 8, 120.98], ['방콕', 7, 100.50], ['하노이', 7, 105.85],
    ['호치민', 7, 106.70], ['자카르타', 7, 106.85], ['델리', 5.5, 77.21],
    ['두바이', 4, 55.27], ['모스크바', 3, 37.62],
    ['런던', 0, -0.13], ['파리', 1, 2.35], ['베를린', 1, 13.40], ['로마', 1, 12.50],
    ['뉴욕', -5, -74.01], ['토론토', -5, -79.38], ['시카고', -6, -87.63],
    ['덴버', -7, -104.99], ['로스앤젤레스', -8, -118.24], ['샌프란시스코', -8, -122.42],
    ['시애틀', -8, -122.33], ['밴쿠버', -8, -123.12], ['호놀룰루', -10, -157.86],
    ['상파울루', -3, -46.63], ['시드니', 10, 151.21], ['멜버른', 10, 144.96],
    ['오클랜드', 12, 174.76],
  ];

  /** 값 문자열 → { name, lon, tzOffset|null }  (tzOffset null이면 한국 = 엔진이 역사적 표준시 자동 처리) */
  function resolve(value) {
    if (!value || value === 'KR:서울') return { name: '서울', lon: 126.98, tzOffset: null };
    const [kind, name] = String(value).split(':');
    if (kind === 'KR') {
      const f = KOREA.find(c => c[0] === name);
      return f ? { name: f[0], lon: f[1], tzOffset: null } : { name: '서울', lon: 126.98, tzOffset: null };
    }
    const f = ABROAD.find(c => c[0] === name);
    return f ? { name: f[0], lon: f[2], tzOffset: f[1] } : { name: '서울', lon: 126.98, tzOffset: null };
  }

  function options() {
    let h = '<optgroup label="한국">';
    h += KOREA.map(c => `<option value="KR:${c[0]}">${c[0]}</option>`).join('');
    h += '</optgroup><optgroup label="해외">';
    h += ABROAD.map(c => `<option value="AB:${c[0]}">${c[0]} (UTC${c[1] >= 0 ? '+' : ''}${c[1]})</option>`).join('');
    h += '</optgroup>';
    return h;
  }

  global.ChaeksaPlaces = { KOREA, ABROAD, resolve, options };
})(window);
