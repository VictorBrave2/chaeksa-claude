    // 辰중 戊 는 지장간이라 명령이 아니라 재료다. 국에 들면 그 자리가 수 명령을 받으므로
    // 토로서의 노릇을 못 한다. 다만 戊 가 **천간에 투출하면** 그건 명령이므로 발동한다.
    //
    // 통근과는 축이 다르다 — 申 은 국에 들어도 庚 의 뿌리다(L11).
