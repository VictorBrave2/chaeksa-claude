    // 통근과는 축이 다르다 — 申 은 국에 들어도 庚 의 뿌리다(L11).
    //   통근      천간이 지지에서 힘을 받는 통로.   국이 안 뺏는다
    //   지장간 십신  그 자리가 무슨 노릇을 하는가.   국에 먹히면 잃는다
    const 국 = E.samhapOf ? E.samhapOf(지지) : [];
