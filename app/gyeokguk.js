  /** 자평진전 성패 판정. 격 이름은 typecard.gyeok 이 정한 것을 그대로 쓴다. */
  function judge(R, 격이름) {
    const T = global.ChaeksaTypecard;
    const 격 = 격이름 || (T && T.gyeokName ? T.gyeokName(R) : null);
    const 표 = 격 && 격표[격];
    if (!표) return { 격, 판정: '미상', ok: 0, 상신: null, 근거: [] };

    const m = 재료(R);
    const 맞은 = (목록) => (목록 || []).filter(([f]) => { try { return !!f(m); } catch (e) { return false; } });

    const 성 = 맞은(표.성), 패 = 맞은(표.패), 기 = 맞은(표.기), 구 = 맞은(표.구);

    // 성 조건이 하나도 안 맞으면 **상신이 없다.** 평주가 이를 「孤官無輔, 同為破格」
    // — 관이 외로워 보좌가 없으니 똑같이 파격 — 이라 못박았다.
    // 자평진전의 핵심은 격이 아니라 상신이므로, 상신이 없으면 격이 못 선다.
    let 판정, ok;
    // 병(帶忌)에 약(救應)이 들면 낫는다 — 格中如去病.
    // **약은 병마다 정해져 있다.** 원문 救應 목록이 병 이름을 부르며 약을 대므로,
    // 그 짝을 격표 구 행의 넷째 칸(고치는병)에 적어 두었다. 짝이 맞는 약만 병을 고친다.
    // 「구 조건이 아무거나 서면 낫는다」로 짜면 상관이 병인데 칠살 합거를
    // 약으로 대는 일이 생긴다 — 실측으로 확인하고 되돌린 자리다(2026-08-31).
    const 병이름 = 기.map(v => v[1]);
    const 약 = 구.filter(v => v[3] && v[3].고침 && v[3].고침.some(b => 병이름.indexOf(b) >= 0));

    if (성.length && 기.length && 약.length) { 판정 = '구제됐다'; ok = 1; }
    else if (성.length && 기.length)  { 판정 = '띠었다';   ok = 0; }
    else if (성.length)               { 판정 = '섰다';     ok = 1; }
    else if (패.length && 구.length)  { 판정 = '구제됐다'; ok = 1; }
    else if (패.length)               { 판정 = '깨졌다';   ok = 0; }
    else                              { 판정 = '깨졌다';   ok = 0; 패.push([null, '상신이 없다 — 고관무보(孤官無輔)']); }

    // 상신 — 격을 세운 조항이 지목한 것. 구제로 살았으면 구제한 글자가 상신이다.
    // 상신은 **격을 세우는 글자**다. 구제로 살았으면 구제한 글자가 상신 노릇을 한다.
    // 「성.length ? 성 : 구」로 바꿔 봤다가 되돌렸다 — 성도 패도 안 선 명(고관무보,
    // 상신이 없다고 판정한 자리)에 구 조건만으로 상신이 붙어, 지목률이 81.4%에서
    // 83.9%로 **없는 상신만큼 올랐다**(2026-08-31).
    // 성 조건이 섰으면 그것이 상신이다(병이 나은 명 포함 — 격을 세운 건 성이다).
    // 성이 하나도 없이 구제로만 산 명에서만 구제한 글자가 상신 노릇을 한다.
    // 「성.length ? 성 : 구」로 뭉뚱그리면 성도 패도 안 선 명(고관무보 — 상신이
    // 없다고 판정한 자리)에 상신이 붙어 지목률이 없는 만큼 오른다(2026-08-31 실측).
    const 상신 = ((판정 === '구제됐다' && !성.length) ? 구 : 성)
      .map(v => v[2]).filter(Boolean)[0] || null;

    return {
      격, 판정, ok, 상신,
      근거: {
        섰다: 성.map(v => v[1]),
        깨졌다: 패.map(v => v[1]),
        띠었다: 기.map(v => v[1]),
        // 병이 나은 명은 **짝이 맞는 약만** 근거로 낸다 — 안 그러면 상관이 병인데
        // 칠살 합거가 약으로 화면에 나간다. 파격을 구한 명은 예전대로 구 전부를 낸다.
        구제: (약.length ? 약 : 구).map(v => v[1]),
      },
      잰것: {
        일간: Math.round(m.일간힘 * 100) / 100,
        비겁: Math.round(m.힘.비겁 * 100) / 100,
        식상: Math.round(m.힘.식상 * 100) / 100,
        재성: Math.round(m.힘.재성 * 100) / 100,
        관성: Math.round(m.힘.관성 * 100) / 100,
        인성: Math.round(m.힘.인성 * 100) / 100,
      },
    };
  }

