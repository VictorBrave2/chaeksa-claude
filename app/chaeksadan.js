  function 공주님말(t) {
    let s = String(t == null ? '' : t);
    if (!/[가-힣]/.test(s)) return s;
    // 「(관성)」처럼 괄호로 덧붙인 십신 이름은 통째로 뗀다 — 앞말이 이미 공주님말이다
    s = s.replace(new RegExp('\\(' + 십신식 + '\\)', 'g'), '');
    // 「壬(임·편관)」 — 읽기 뒤에 붙은 십신 이름만 뗀다
    s = s.replace(new RegExp('·' + 십신식 + '\\)', 'g'), ')');
    조문말.forEach(([a, b]) => { s = s.split(a).join(b); });
    s = s.replace(격식, (m, k, to) => { const w = 찾(k) + ' 짜임'; return w + 토바꿈(w, to); });
    s = s.replace(/(^|[\s「(])격(이|은|을|만|도|의|에|인지)/g, (m, a, to) => a + '짜임' + 토바꿈('짜임', to));
    // 「상관없이」「편인가」처럼 딴 말의 일부인 것은 건드리지 않는다
    s = s.replace(낱식, (m, k, to, off, all) => {
      if (k === '상관' && /없/.test(all.slice(off + 2, off + 3))) return m;
      if (k === '편인' && to === '가') return m;
      const w = 찾(k); return w + 토바꿈(w, to);
    });
    // 「튀는 말과 재주인 튀는 재주가」 — 꾸밈말이 이미 설명이니 뒤의 낱말을 뗀다
    s = s.replace(/([가-힣])인 (바른 자리|거센 자리|자리 글자|자리|쌓이는 돈|움직이는 돈|돈|기르는 힘|받치는 힘|받쳐 주는 힘|내놓는 재주|튀는 재주|재주|나와 같은 기운|겨루는 기운|나눠 갖는 기운|센 칼|제 뿌리)(이|가|은|는|을|를|과|와|으로|로)?/g,
      (m, c, w, to) => c + 토바꿈(c, to));
    // 같은 말이 두 번 붙으면 하나로 — 「받쳐 주는 받쳐 주는 힘」「튀는 튀는 재주」
    // 바꿔 넣은 꾸밈말만 — 「이 이 해」 같은 진짜 말은 건드리지 않는다
    s = s.replace(/(받쳐 주는|나와 같은|나눠 갖는) \1/g, '$1').replace(/(튀는|내놓는|받치는|기르는|겨루는|쌓이는|움직이는|바른|거센) \1/g, '$1');
    // 말끝은 층을 아는 자리(열눈·의논)에서만 건다. 층을 모르는 문장은 쓴 대로 둔다 —
    // 사장님 09-04 저녁 「~어요 가능. 목표 말고는 제한 없음」. 물음표 문장이 「~일 수 있습니다?」로 망가지던 자리.
    // 「글자이」처럼 괄호를 뗀 뒤 남은 토
    s = s.replace(/글자이(?=[\s,.])/g, '글자가').replace(/글자은(?=[\s,.])/g, '글자는').replace(/글자을(?=[\s,.])/g, '글자를');
    return s;
  }
