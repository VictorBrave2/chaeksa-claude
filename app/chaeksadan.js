    // 그 봉우리가 스무 해 안쪽일 것. 마흔한 살에게 여든의 봉우리를 근거로
    // 「기다리셔도 됩니다」라고 하면 그건 백지수표다.
    // 그리고 「뒤로 갈수록 두터워진다」는 약속을 걷어냈다 — 곡선은 곧장 오르지 않는다.
    // 봉우리가 어느 칸인지 이름을 대서, 그것이 언제인지 공주님이 직접 보시게 한다.
    const u = F.운로, 현 = F.연애현재;
