  // 십신 — 엔진에 공개된 함수가 없어 여기서 센다.
  // 오행 목화토금수 0~4, 생은 +1, 극은 +2. 음양이 같으면 편, 다르면 정.
  function 십신of(R, 글자) {
    try {
      const E = global.ChaeksaEngine;
      const o = E.STEMS.indexOf(글자), d = R.pillars.day.stem;
      if (o < 0) return null;
      const de = E.STEM_ELEM[d], oe = E.STEM_ELEM[o];
      const 같음 = (d % 2) === (o % 2);
      if (oe === de) return 같음 ? '비견' : '겁재';
      if (oe === (de + 1) % 5) return 같음 ? '식신' : '상관';
      if (oe === (de + 2) % 5) return 같음 ? '편재' : '정재';
      if (de === (oe + 2) % 5) return 같음 ? '편관' : '정관';
      if (de === (oe + 1) % 5) return 같음 ? '편인' : '정인';
      return null;
    } catch (e) { return null; }
  }
