    // 절을 나누는 원칙 — **한 절은 한 물음이다.**
    //   몸(억부)과 일(천직)은 다른 물음인데 「타고난 결」 한 절에 묶여 있었고,
    //   그래서 「돈과 일을 두고」에는 일이 없었다. 갈림_돈일 이 장현을 부르는데
    //   장현이 딴 절에 있는 모순도 거기서 나왔다.
    //   재관은 한 자리에서 본다 — **財는 영역의 산출이다**(docs/27 영역관제).
    const 몸 = []; 형준(몸, F, s);
