    //   「버팀목이십니다」는 「당신은 이런 사람입니다」라 반증이 안 된다.
    //   「받치는 자리에 서 계십니다」는 읽는 순간 맞다/아니다가 갈린다.
    // 판정은 그대로다 — c.유형·c.풀이·c.축을 한 글자도 안 바꿨다.
    // 인용 관형형 — 「~다」는 「~다는」이지만 **「~이다」는 「~이라는」**이다.
    // 그냥 '는'을 붙이면 「쪽이다는 자리예요」가 나온다(25유형 중 둘).
    const 인용 = (v) => /이다$/.test(v) ? v.replace(/이다$/, '이라는') : v + '는';
    말(L, '천직', 머리 + ' 공주님한테 어울리는 자리는 ' + c.유형 + ' 쪽이에요.'
      + (c.풀이 ? ' ' + 인용(c.풀이) + ' 자리라서요.' : '')
      + (c.축 ? ' 거기서는 ' + 을를(c.축) + ' 주로 쓰게 돼요.' : ''));
    // c.근거[0] 은 「신약 — 좋은 조직·좋은 사람 옆에서 몇 배가 된다」 꼴이라
