  // 코러스는 한 사람 한 문장·여섯 줄까지였다. 여기는 그 화면의 절에 든 마디를 **전부**,
  // 책사별로 묶어 돌려준다. 목 가다듬는 문장(「저울은 제가 들겠습니다」)만 걷어내고 나머지는 그대로.
  // 객체로 돌려주니 번호 칸이 없다. 값이 있는 사람은 전부, 있는 만큼.
  function 다듬기(t) {
    const 문 = String(t || '').split(/(?<=[.!?])\s+/).map(x => x.trim()).filter(Boolean);
    // 짧은 인사(「자리 이야기도 하나 하겠습니다」)는 「자리」가 값말에 걸려도 인사다 —
    // 길이로 가른다. 값 없는 짧은 문장(「달까지 나왔군요」)도 군말이다.
    const 남 = 문.filter(s => !((인사말.test(s) && s.length < 60) || (!값말.test(s) && s.length < 22)));
    return 남.join(' ');
  }
  function 열눈(R, now, tab) {
    const 절들 = 코러스절[tab]; if (!절들) return [];
    const 모 = 모으기(R, now); if (!모) return [];
    const 묶 = []; const 본 = {};
    절들.forEach(k => (모.절[k] || []).forEach(m => {
      const t = 다듬기(m.본문); if (!t || 본[t]) return; 본[t] = 1;
      let g = 묶.find(x => x.축 === m.축); if (!g) { g = { 축: m.축, 본문들: [], 층들: [] }; 묶.push(g); }
      g.본문들.push(t); g.층들.push(m.층 || '잣대');
    }));
    if (묶.length > 1) {
      const d = Math.floor((now || new Date()).getTime() / 86400000) % 묶.length;
      return 묶.slice(d).concat(묶.slice(0, d));
    }
    return 묶;
  }

