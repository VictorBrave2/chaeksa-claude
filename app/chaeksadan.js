    //   「어울리는 일로는 건설 쪽입니다」 → 「난 건설 안 하는데」에서 닫힌다.
    //   「이런 자리는 보통 이런 데서 보입니다」 → 「어 나 그런데?」로 이용자가 스스로 잇는다.
