    // 조항은 판정키다 — 화면에는 공주님말을 낸다(gyeokguk.js 공주님말표).
    // 아래 갈림_뼈대(325줄)는 십신 이름을 조항에서 찾으므로 **원래 조항 그대로** 쓴다.
    const 갖 = 읽말((j.갖춤 || [])[0]), 무 = 읽말((j.무너짐 || [])[0]);
