    //   병이 나았다 — 격은 섰는데 걸리는 것이 있었고, 그것을 풀어 주는 것이 있다(성·기·구)
    //   깨진 것을 구했다 — 격이 못 섰는데 받쳐 주는 것이 있다(패·구)
    const 병나음 = j.판정 === '구제됐다' && (j.갖춤 || []).length > 0;
