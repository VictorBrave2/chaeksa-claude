  function 장현(L, F, s, R) {          // 천직 — 일의 결
    const c = F.천직; if (!c) return;
    const 머리 = 골라(['일 이야기는 제가 하겠습니다.', '먹고사는 쪽을 맡겠습니다.', '손에 잡히는 이야기를 하겠습니다.'], s, '장현.머리');
    // **존재가 아니라 위치로 말한다**(docs/27 아홉 — 신뢰도는 반증 가능성에서 온다).
    //   「버팀목이십니다」는 「당신은 이런 사람입니다」라 반증이 안 된다.
    //   「받치는 자리에 서 계십니다」는 읽는 순간 맞다/아니다가 갈린다.
    // 판정은 그대로다 — c.유형·c.풀이·c.축을 한 글자도 안 바꿨다.
    // 인용 관형형 — 「~다」는 「~다는」이지만 **「~이다」는 「~이라는」**이다.
    // 그냥 '는'을 붙이면 「쪽이다는 자리예요」가 나온다(25유형 중 둘).
    const 인용 = (v) => /이다$/.test(v) ? v.replace(/이다$/, '이라는') : v + '는';
    말(L, '천직', 머리 + ' 공주님이 서 계신 자리는 ' + c.유형 + ' 쪽입니다.'
      + (c.풀이 ? ' ' + 인용(c.풀이) + ' 자리예요.' : '')
      + (c.축 ? ' ' + 을를(c.축) + ' 주력으로 씁니다.' : ''));
    // c.근거[0] 은 「신약 — 좋은 조직·좋은 사람 옆에서 몇 배가 된다」 꼴이라
    // 이미 완결된 말이다. 여기에 「~는 자리입니다」를 덧대고 있었다(한 판에 최대 4회).
    // **영역이 「어울리는 일」보다 먼저다**(docs/27). 한 사람당 셋까지라 순서가 곧 우선순위다.
    영역(L, F, s, R);
    // **처방이 아니라 서술이다**(docs/27 아홉). 직업은 이용자가 정한다.
    //   「어울리는 일로는 건설 쪽입니다」 → 「난 건설 안 하는데」에서 닫힌다.
    //   「이런 자리는 보통 이런 데서 보입니다」 → 「어 나 그런데?」로 이용자가 스스로 잇는다.
    // 예시는 빼지 않는다 — **공감의 사다리**다. 바꾸는 것은 틀뿐이다.
    const 곳 = ((c.근거 || [])[0] ? String(c.근거[0]).replace(/^[^—]*—\s*/, '') + '는 편이에요.' : '')
      + (c.일들 ? (((c.근거 || [])[0] ? ' ' : '') + '이런 자리는 보통 ' + c.일들 + ' 같은 데서 보입니다.') : '');
    if (곳) 말(L, '천직', '어디서 그 자리가 보이는지도 말씀드릴게요. ' + 곳);
  }

  /** 영역 — 官을 벼슬이 아니라 **내가 맡은 판**으로 읽는다(docs/27 영역관제).
   *
   *  **새 계산을 지어내지 않는다.** 자평진전이 이미 잰 십신 세력(F.자평진전.힘)을
   *  삶의 말로 옮길 뿐이다. 새 상수도 없다 — 있는 값끼리 비교만 한다(docs/13 「輕重은 비교로만」).
   *
   *  힘은 **천간에 드러난 것**의 합이다. 영역은 드러난 자리를 말하므로 투출로 읽는 것이 맞다.
   *
   *  官이 없다고 나쁘게 읽지 않는다 — 그건 貴賤의 다른 이름이다.
   *  자리가 없으면 운에서 받거나 자기가 만든다. */
  /** 영역 — 官과 나머지 넷의 관계(docs/27). **계산은 typecard.영역축() 한 곳에 있다.**
   *  여기서는 뚜렷한 하나(둘)만 말한다. 팽팽한 축은 단정할 근거가 없다 —
   *  애매한 것을 단정하면 그게 지어내는 것이다. 넷을 다 펼치는 것은 職 탭이 한다. */
  function 영역(L, F, s, R) {
    const T = global.ChaeksaTypecard;
    if (!T || !T.영역축) return;
    const 축 = T.영역축((F.자평진전 || {}).힘, (F.천직 || {}).축 || '', R);
    if (!축.length) return;
    const 머리 = 골라(['자리 이야기도 하나 하겠습니다.', '한 가지만 더 — 자리 쪽입니다.',
                       '일과 붙어 있는 이야기라 여기서 말씀드릴게요.'], s, '장현.영역머리');
    // 어떻게 얻은 자리인가(docs/28 3순위) — 첫 마디에 붙인다. 따로 내면 장현이 네 마디가 되어 잘린다
    // (「흔들림」이 그래서 0.0% 였다). 관없음은 세 갈래 문장이 이미 그 얘기라 안 붙인다.
    const 내 = (축[0].이름 !== '관없음' && T.자리내력) ? T.자리내력((F.자평진전 || {}).힘) : null;
    말(L, '천직', 머리 + ' ' + 축[0].말 + (내 ? ' ' + 내.말 : ''));
    if (축[1] && 축[1].기울기 >= 0.34) 말(L, '천직', 축[1].말);
    // 「어디에 서 있나」 다음은 「언제 문이 가까운가」다(docs/28 넷 1순위).
    // **官의 얼굴 하나만 쓴다** — 인연 쪽은 연희 몫이고, 둘을 한 사람이 말하면
    // 한 문장 두 주장이 된다(제24조 · docs/28 다섯).
    if (R && T.영역해) {
      try {
        const y = T.영역해(R, new Date().getFullYear(), 10);
        if (y.첫해) {
          // 열림과 흔들림을 **한 마디에** 담는다. 따로 내보냈더니 장현이 네 마디가 되어
          // 뒤가 통째로 잘렸다 — 3000판에서 「흔들림」 실림 0.0%였다.
          // 한 문장에 두 주장을 넣는 것과는 다르다(제24조). 문장을 나누고 마디만 합친다.
          // 겁주지 않는다 — 「무너진다」가 아니라 「건드린다」다. 받침이 있으면 그것도 적힌다.
          // 견관이 있으면 그것을 먼저 붙인다 — 그 해 자체의 이야기라 더 가깝다.
          // 없을 때만 다른 해(흔들해)로 넘어간다. 둘 다 붙이면 마디가 길어져 잘린다.
          const 흔 = (y.흔들해 && y.흔들해[0]);
          말(L, '천직', '때도 같이 보겠습니다. ' + y.첫해.해 + '년 ' + y.첫해.간지
            + ' — ' + y.첫해.이유[0] + '. 앞으로 열 해 중 자리 쪽으로 가장 가까운 해입니다.'
            + (y.첫해.견관 ? ' ' + y.첫해.견관
               : 흔 ? ' 반대로 ' + 흔.해 + '년은 ' + 흔.흔들 + '.' : ''));
        }
      } catch (e) {}
    }
  }

