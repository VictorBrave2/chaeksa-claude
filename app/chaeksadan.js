    //   장현이 딴 절에 있는 모순도 거기서 나왔다.
    //   재관은 한 자리에서 본다 — **財는 영역의 산출이다**(docs/27 영역관제).
    const 몸 = []; 형준(몸, F, s);
    const 자리 = []; 성아(자리, F, s, R);
    const 사랑 = []; 연희(사랑, F, s); 갈림_사랑(사랑, F);
