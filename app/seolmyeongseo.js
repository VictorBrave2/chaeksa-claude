      + (조건줄 ? '<div class="sm-head"><b>잘 도는 조건</b>' + 딱지('명리 해석') + '</div>' + 조건줄 : '')
      + (막힘줄 ? '<div class="sm-head"><b>막힐 수 있는 곳</b>' + 딱지('명리 해석') + '</div>' + 막힘줄 : '')
      + 지금줄 + 제안 + 제외 + 다름줄
      + '<div class="sm-head"><b>내 경험 적어 두기</b>' + 딱지('알려주신 것') + '</div>'
      + '<textarea class="sm-memo" id="smMemo" rows="3" placeholder="위 질문에 답해 보시거나, 실제로 어땠는지 적어 두세요. 이 기기에만 저장돼요.">' + esc(기.메모 || '') + '</textarea>'
      + '<div class="sm-btns"><button class="btn ghost small" id="smDiff">' + (기.다름 ? '다시 맞다고 하기' : '내 경험과 다릅니다') + '</button></div>'
      + '<p class="sm-limit">이 설명서는 하나의 해석 틀로 본 것이에요. 맞혔다는 뜻이 아니라, 이렇게 봤으니 실제 겪은 일과 대 보시라는 뜻이에요.</p>';

    box.innerHTML =
      '<section class="sm" data-plain="1">'
      + '<div class="sm-title"><b>내 구조를 이해하는 설명서</b><span>무엇을 받아들이고, 어떻게 만들어 내는가</span></div>'
