    // ① 장면
    const 머리 = d.장면
      ? '<p class="sm-scene"><b>' + esc(d.장면.이름) + '</b></p><p class="sm-draw">' + esc(d.장면.그림) + '</p>'
      : '<p class="sm-scene"><b>장면은 붙이지 않았어요</b></p><p class="sm-draw">' + esc(d.보류 || '고를 만한 장면이 없어요.') + ' 확인된 것만 아래에 적어요.</p>';

    // 사슬 다섯 마디 — 회사 칸 이름을 십신 이름 밑에 붙인다. 격이 고른 입구 칸에는 「시작」 표시.
