      + (조건줄 ? '<div class="sm-head"><b>잘 풀리는 때</b>' + 딱지('사주로 본 것') + '</div>' + 조건줄 : '')
      + (막힘줄 ? '<div class="sm-head"><b>막히는 때</b>' + 딱지('사주로 본 것') + '</div>' + 막힘줄 : '')
