  /** 격 이름 → 사슬 마디. 격이 정하는 부품을 말하기 위해서다. */
  function 격마디(격이름) {
    const n = String(격이름 || '');
    if (/인|인수/.test(n)) return '받는';
    if (/식신|상관/.test(n)) return '내놓는';
    if (/재/.test(n)) return '모이는';
    if (/관|살/.test(n)) return '불러가는';
    if (/록|인|비견|겁/.test(n)) return '나';
    return null;
  }

  /** 글자 자리 채우기 — 마디에 살아 있는 글자가 있으면 「경금(庚) 정재」, 없으면 「운에서 올 솥(재성)」. */
  function 글자말(m, 부품) {
    if (!m) return '';
    const 들 = (m.글자들 && m.글자들.length) ? m.글자들 : (m.속글자들 || []);
    if (들.length) return 묶어(들.map(g => g.글자 + ' ' + g.십신));
    return '운에서 올 ' + 부품[m.key] + '(' + m.이름 + ')';
  }

  /** 조건·막힘 문장의 {A}~{E} 를 실제 글자로 채운다. */
  function 채우기(문, ch, 부품, 비겁들) {
    const s = (k) => ch.find(x => x.key === k);
    const 자리 = {
      A: 글자말(s('받는'), 부품), B: 글자말(s('내놓는'), 부품), C: 글자말(s('모이는'), 부품), D: 글자말(s('불러가는'), 부품),
      E: 비겁들.length ? 묶어(비겁들) : '운에서 올 ' + 부품.같은 + '(비겁)',
    };
    // 조사는 글자 뒤에 따로 붙어 있어서(「{C}가」) 받침만 맞춘다.
    return 문.replace(/\{([A-E])\}(가|이|를|을|는|은|와|과|으로|로)?/g, (all, k, j) => {
      const v = 자리[k];
      if (!j) return v;
      if (j === '가' || j === '이') return 이가(v);
      if (j === '를' || j === '을') return 을를(v);
      if (j === '는' || j === '은') return 은는(v);
      if (j === '로' || j === '으로') return 조(v, '으로', '로');
      return 조(v, '과', '와');
    });
  }

