    const 지금줄 = d.지금 && d.지금.범주
      ? '<div class="sm-now"><b>' + esc(d.기간) + (d.지금.간지 ? ' · ' + esc(d.지금.간지) : '') + '</b><p>' + esc(d.지금.근거 || '') + '</p>'
        + '<p class="sm-note">이건 이 기간에만 해당해요. 위의 기본 설명은 그대로예요.</p></div>'
      : '';

    // ⑤⑥ 제안 — 「다름」 표시가 있으면 감춘다
    const 제안 = (!d.장면 || 기.다름) ? '' :
      '<div class="sm-head"><b>현실에서 확인해 보세요</b>' + 딱지('책사의 제안') + '</div>'
      + d.장면.질문.map(s => '<p class="sm-q">' + esc(s) + '</p>').join('')
      + '<div class="sm-head"><b>작게 해볼 것</b>' + 딱지('책사의 제안') + '</div>'
      + '<p>' + esc(d.장면.실험) + '</p>';

