  const 쓰기 = (o) => { try { localStorage.setItem(KEY, JSON.stringify(o)); } catch (e) {} };
  function 기록(pid) { return 읽기()[pid || 'me'] || { 다름: false, 메모: '' }; }
  function 기록쓰기(pid, v) { const all = 읽기(); all[pid || 'me'] = Object.assign(기록(pid), v); 쓰기(all); }

