      if (du) { 대운없음 = false; 대운 = e.fmt.pillar(du); 대운나이 = { start: du.startAge, end: du.endAge };
        if (!세운만) { 넣(du.stem, '대운', '하늘'); 넣((e.HIDDEN[du.branch] || [])[0], '대운', '땅'); } }
