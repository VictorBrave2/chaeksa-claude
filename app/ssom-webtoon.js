/* 연애궁합 개인화 웹툰 — 뼈대 + 조각 조립기(docs/75, 작업판 21). 09-25 시범: 썸 1 · 2회.
 * 아무 두 명식이 와도 그 둘의 웹툰이 나오게: 줄거리 · 소재 · 책사 물음은 뼈대(공통), 대사 · 해설은 조각으로 끼운다.
 * 뼈대 줄: ['장면'|'당신'|'상대'|'인연'|'좌장', 말] = 그대로
 *          ['@언행', 누구]   → 조각.언행[회][그 사람 언행키]   (식신/상관 × 드러남/숨음 · 없음 — 5)
 *          ['@바람', 누구]   → 조각.바람[회][그 사람 바람]     (일지 십신 10)
 *          ['@한마디', 누구] → 조각.한마디[회][그 사람 바람]   (그 사람에게 건넬 말 — 받는 쪽 바람 10)
 *          ['@단서', 종류, 누구] → 엔진 문장 틀(종류: 바람 · 언행) — 쓰지 않는다
 * 조각 안의 줄은 '당신' · '상대' 대신 '나' · '너'로 쓴다: '나' = 그 조각의 주인(누구), '너' = 맞은편. 조립 때 당신/상대로 바뀐다.
 * 책사 해설의 「이 분」 · 「상대분」도 조각 안에선 {나분} · {너분}으로 쓴다. */
(function (global) {
  const E = global.ChaeksaEngine, S = global.ChaeksaSsom;
  const 행 = '木火土金水';
  const 받침 = (ko) => { const c = ko.charCodeAt(ko.length - 1) - 0xAC00; return c >= 0 && c % 28 !== 0; };
  const 는 = (ko) => 받침(ko) ? '은' : '는';
  function 사람(R) {
    const ds = R.pillars.day.stem, br = R.pillars.day.branch, 언 = (S.언행(R) || [])[0];
    const 본 = (E.HIDDEN[br] || [])[0], 본기 = typeof 본 === 'number' ? 본 : 본[0];
    return { R, 일간: E.STEMS[ds] + 행[E.STEM_ELEM[ds]], 일지: E.BRANCHES[br], 본기: E.STEMS[본기], 본기ko: E.STEMS_KO[본기], 바람: S.일지십신(R),
      언: 언 || null, 언행키: 언 ? 언.십신 + (언.드러남 ? '드러남' : '숨음') : '없음' };
  }
  const 언행뜻 = { 식신: '챙겨 주는 쪽', 상관: '방법과 할 말을 먼저 내놓는 쪽' };
  function 단서(종류, p) {
    if (종류 === '바람') return p.일간 + '에게 배우자궁 ' + p.일지 + ' 속 ' + p.본기 +는(p.본기ko) + ' ' + p.바람 + ', ' + ((S.바라는사람 || {})[p.바람] || '') + '을 바라요.';
    if (!p.언) return p.일간 + '에게는 식신 · 상관이 없어서, 대하는 방식은 식상으로 말할 단서가 적어요.';
    const g = p.언.글자, gko = E.STEMS_KO[E.STEMS.indexOf(g)];
    return p.일간 + '에게 ' + g + 는(gko) + ' ' + p.언.십신 + '이라 ' + 언행뜻[p.언.십신] + '이에요. '
      + (p.언.드러남 ? '천간에 드러나 있어서 해 준 건 티를 내요.' : '지장간에 숨어 있어서 해 준 걸 생색내지 않아요.');
  }

  const 뼈대 = {
    썸: [
      [
        ['장면', '처음 만난 날에서 한 주 뒤. 둘이 처음 따로 만난 카페. 그 사람 노트북이 갑자기 먹통이 된다.'],
        ['상대', '아 망했다, 내일 발표 자료 여기 있는데…'],
        ['@언행', '당신'],
        ['좌장', '상대분은 이 분 어디에 끌려?'],
        ['@바람', '상대'],
        ['@단서', '바람', '상대'],
        ['좌장', '이 분이 해 볼 말은?'],
        ['@한마디', '상대'],
      ],
      [
        ['장면', '목요일 밤, 통화. 당신은 하루 종일 회의에 시달렸다.'],
        ['@언행', '당신'],
        ['@언행', '상대'],
        ['@바람', '당신'],
        ['@단서', '바람', '당신'],
        ['@한마디', '당신'],
      ],
    ],
  };

  // 조각 — 09-25 시범은 丁卯(편인 · 상관숨음) × 丙午(겁재 · 상관드러남) 칸만 차 있다. 빈 칸은 「쓰고 있어요」.
  const 조각 = {
    썸: [
      {
        언행: {
          상관숨음: [
            ['장면', '{나}은 말없이 노트북을 가져가 이것저것 눌러 본다. 십 분 뒤, 화면이 켜진다.'],
            ['너', '헐 어떻게 한 거예요?'],
            ['나', '그냥… 설정 하나 바꿨어요. 근데 이거 구조 은근 재밌네요. 이거 보세요.'],
            ['장면', '{나}이 화면을 돌려 보여 준다. {너}이 몸을 기울여 같이 들여다본다.'],
          ],
        },
        바람: {
          겁재: [
            ['인연', '고쳐 준 것보다, 마지막에 「재밌네요, 이거 보세요」 한 거요. 그때 같이 신났잖아요.'],
            ['인연', '{나분}은 도움 받는 것보다 옆에서 같이 들뜨는 순간을 기억해요.'],
          ],
        },
        한마디: {
          겁재: [['인연', '뭘 도와줬을 때 설명 말고 이거요. 「이거 같이 해 보니까 재밌다.」']],
        },
      },
      {
        언행: {
          상관숨음: [['장면', '{나}은 아무 말도 안 했다.']],
          상관드러남: [['나', '근데 오늘 목소리 왜 그래요? 무슨 일 있었죠?']],
        },
        바람: {
          편인: [
            ['장면', '{나}은 잠깐 말을 멈춘다. 이번이 두 번째다. 말 안 했는데 알아챈 게.'],
            ['좌장', '{나분}은 왜 이 사람한테 마음이 가?'],
            ['인연', '말 안 해도 알아채 주니까요. {나분}이 제일 바라는 사람이 그런 사람이에요.'],
            ['좌장', '{너분}이 늘 그래 줄까?'],
            ['인연', '거기가 걸려요. {너분}은 기분이 들뜰 땐 자기 얘기로 바빠요. 알아채는 게 중심인 사람은 아니에요.'],
            ['인연', '{나분}은 「이 사람은 날 알아봐 주는 사람」이라고 믿기 시작했어요. 기대가 커지면 못 알아챈 날 서운해져요.'],
          ],
        },
        한마디: {
          편인: [['인연', '지금은 그냥 고마워하면 돼요. 알아채 주길 기다리지 말고, 힘든 날은 먼저 한 줄 말해 두는 게 편해요.']],
        },
      },
    ],
  };

  function 조립(나R, 그R, 단계) {
    const 틀 = 뼈대[단계]; if (!틀) return null;
    const 사 = { 당신: 사람(나R), 상대: 사람(그R) };
    const 맞은 = { 당신: '상대', 상대: '당신' };
    const 이름 = { 당신: '당신', 상대: '그 사람' }, 분 = { 당신: '이 분', 상대: '상대분' };
    return 틀.map((회, i) => {
      const 칸 = ((조각[단계] || [])[i]) || {}, out = [];
      회.forEach(줄 => {
        const [종, a, b] = 줄;
        if (종 === '@단서') { out.push(['단서', 단서(a, 사[b])]); return; }
        if (종[0] !== '@') { out.push([종, a]); return; }
        const 누 = a, 너 = 맞은[누], 키 = 종 === '@언행' ? 사[누].언행키 : 사[누].바람;
        const 조 = ((칸[종.slice(1)] || {})[키]);
        if (!조) { out.push(['장면', '(' + 이름[누] + ' — ' + 키 + ' 조각은 쓰고 있어요)']); return; }
        조.forEach(([w, 말]) => out.push([w === '나' ? 누 : w === '너' ? 너 : w,
          말.replace(/\{나\}/g, 이름[누]).replace(/\{너\}/g, 이름[너]).replace(/\{나분\}/g, 분[누]).replace(/\{너분\}/g, 분[너])]));
      });
      return out;
    });
  }
  global.ChaeksaSsomWebtoon = { 조립, 사람, 단서, 뼈대, 조각 };
})(window);
