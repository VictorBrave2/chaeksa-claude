  /** 궁합 결론 셋 — 서로 보완 / 서로 깎음 / 한쪽이 기대는 사이 */
  function 궁합결론(g) {
    if (g.나에게.상태 === '근거 부족' || g.그사람에게.상태 === '근거 부족') return '한쪽의 격을 못 잡아 판단을 미뤄요.';
    if (g.나에게.상태 === '계산 실패' || g.그사람에게.상태 === '계산 실패') return '계산이 안 됐어요.';
    const 셈 = (x, 방향) => x.줄.filter(j => j.방향 === 방향 && !j.같은작용).length;   // 같은 대상의 같은 변화는 한 번만
    const 채움 = (x) => 셈(x, '보완'), 손상 = (x) => 셈(x, '하락');
    // 핵심 손상(격신 합거)이 있으면 보완 몇 개로 덮지 않는다
    const 핵심손상 = (x) => x.줄.some(j => j.갈래 === '격' && j.방향 === '하락');
    if (핵심손상(g.나에게) && 핵심손상(g.그사람에게)) return '서로 격신을 묶어요. 서로 깎는 사이예요.';
    if (핵심손상(g.나에게)) return '그 사람이 내 격신을 묶어요. 다른 보완으로 덮이지 않아요.';
    if (핵심손상(g.그사람에게)) return '내가 그 사람의 격신을 묶어요. 다른 보완으로 덮이지 않아요.';
    const a = 채움(g.나에게) - 손상(g.나에게), b = 채움(g.그사람에게) - 손상(g.그사람에게);
    if (a > 0 && b > 0) return '서로 보완하는 사이예요.';
    if (a < 0 && b < 0) return '서로 깎는 사이예요.';
    if (a > 0 && b <= 0) return '내가 그 사람에게 기대는 사이예요.';
    if (b > 0 && a <= 0) return '그 사람이 나에게 기대는 사이예요.';
    return '서로 크게 건드리지 않는 사이예요.';
  }

