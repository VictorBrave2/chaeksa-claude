/* 연애궁합 3초 결과 — 네 단계(09-25 사장님 「상위 25%가 이혼하지 않는다면 4단계로 나누면 딱 맞는 것 아니야? · 원하는 게 있고 원하는 걸 주는 사이 = 파트너」).
 * 숫자 · 배점 · 가중치는 쓰지 않는다(09-25 「점수를 만들어내기 위해 네가 무리하는 경향」). 판정만 센다.
 * 한 방향 = 받는 쪽이 바라는 사람(일지 본기 십신) 을 주는 쪽이 주나.
 *   준다 = ① 주는 쪽 언행(앞선 식상 글자, 없으면 일간)이 바라는 글자와 같거나 · 같은 기운이다(생해 주는 것은 치지 않는다 — 09-25 사장님 「이 조건을 왜 넣는거지」, 근거 없이 내가 넣었던 것), 또는
 *          ② 주는 쪽의 격이 바라는 사람과 같은 십신이다(건록 = 비견 · 양인 = 겁재). 같은 무리(편인 ↔ 정인 등)는 치지 않는다(09-25 사장님 「같은무리를 인정하지 않을게」).
 *   깎는다 = 언행이 바라는 기운을 극하고, 격도 다르다.
 * 단계: 4 파트너(둘 다 준다) · 3 한쪽이 주는 사이(다른 쪽은 안 깎음) · 2 한쪽이 주고 한쪽은 깎는 사이 · 1 아직 주고받지 못하는 사이.
 * 무작위 명식 2만 쌍(씨앗 12345): 28.0 · 32.5 · 16.7 · 22.8% — 판정만으로 넷이 거의 고르게 갈린다.
 * 「준다」에 무엇을 넣을지는 내 추론 — 사장님 검수 대기. 문장은 ChaeksaSsomScoreMal(작가 원고). 일지 합충 · 계절은 넣지 않는다. */
(function (global) {
  const E = global.ChaeksaEngine, S = global.ChaeksaSsom;
  const 본기 = (R) => { const h = (E.HIDDEN[R.pillars.day.branch] || [])[0]; return typeof h === 'number' ? h : h[0]; };
  const 주는글자 = (R) => { const 언 = (S.언행(R) || [])[0]; return 언 ? E.STEMS.indexOf(언.글자) : R.pillars.day.stem; };
  function 관계(받, 주) {   // 받 = 받는 쪽 일지 본기, 주 = 주는 쪽 글자
    if (받 === 주) return '같은글자';
    const a = E.STEM_ELEM[주], b = E.STEM_ELEM[받];
    if (a === b) return '같은기운';
    if ((a + 1) % 5 === b) return '채워줌';
    if ((b + 1) % 5 === a) return '채워줘야';
    if ((b + 2) % 5 === a) return '눌러둠';
    return '엇갈림';
  }
  const 격십신 = { 건록: '비견', 양인: '겁재' };
  function 격맞음(바라는R, 상대R) {
    let 격 = null; try { 격 = global.ChaeksaTypecard.gyeok(상대R).name; } catch (e) { return { 키: '다름', 격: null }; }
    격 = 격십신[격] || 격; const 바람 = S.일지십신(바라는R);
    if (격 === 바람) return { 키: '같음', 격 };
    return { 키: '다름', 격 };
  }
  function 방향(받는R, 주는R) {
    const 관 = 관계(본기(받는R), 주는글자(주는R)), 격 = 격맞음(받는R, 주는R);
    const 준다 = /같은글자|같은기운/.test(관) || 격.키 !== '다름', 깎는다 = 관 === '엇갈림' && 격.키 === '다름';
    return { 관계: 관, 격, 준다, 깎는다 };
  }
  function 재기(나R, 그R) {
    const 나쪽 = 방향(나R, 그R), 그쪽 = 방향(그R, 나R);   // 나쪽 = 당신이 받는 방향
    const 단계 = 나쪽.준다 && 그쪽.준다 ? 4 : 나쪽.준다 || 그쪽.준다 ? ((나쪽.준다 ? 그쪽 : 나쪽).깎는다 ? 2 : 3) : 1;
    const 끌림 = 나쪽.준다 === 그쪽.준다 ? '비슷' : 나쪽.준다 ? '당신' : '그 사람';
    return { 단계, 나쪽, 그쪽, 끌림 };
  }
  const esc = (t) => String(t).replace(/[&<>"]/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[c]);
  function 카드(나R, 그R) {
    const r = 재기(나R, 그R), 말 = global.ChaeksaSsomScoreMal || {}, 단 = (말.단계 || {})[r.단계] || {};
    const 끌 = (말.끌림 || {})[r.끌림] || '', 한 = (k) => (말.관계 && 말.관계[k]) || '';
    const 줄 = (누, d) => 한(d.관계) ? '<p><b>' + 누 + '</b> ' + esc(한(d.관계)) + '</p>' : '';
    const 계 = (누, c) => 말.격 && 말.격[c.키] ? '<p><b>' + 누 + '</b> ' + esc(말.격[c.키]) + '</p>' : '';
    return '<div class="card ss-score"><p class="ss-score-n"><b>' + esc(단.이름 || '') + '</b></p>'
      + (단.한줄 ? '<p class="ss-lead">' + esc(단.한줄) + '</p>' : '')
      + (끌 ? '<p>' + esc(끌) + '</p>' : '')
      + 줄('당신이 바라는 것 →', r.나쪽) + 줄('그 사람이 바라는 것 →', r.그쪽)
      + (r.나쪽.격.키 === r.그쪽.격.키 ? 계('둘 다 →', r.나쪽.격) : 계('그 사람은 →', r.나쪽.격) + 계('당신은 →', r.그쪽.격))
      + '</div>';
  }
  global.ChaeksaSsomScore = { 재기, 카드, 관계 };
})(window);
