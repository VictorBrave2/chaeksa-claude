/* 연애궁합 3초 결과 — 점수 · 누가 더 끌리나(09-25 사장님 「대중이 원하는 건 순위 나열」 · 「3초 결과」 · 「일단 무료로 다 풀고」).
 * 한 축만 잰다(삼체가 되지 않게): 받는 쪽이 바라는 것(일지 본기) × 주는 쪽이 대하는 법(앞선 식상 글자, 없으면 일간 그대로).
 * 두 글자의 오행 관계로 한 방향을 매긴다. 같은 글자 > 같은 기운 > 주는 쪽이 생해 줌 > 받는 쪽이 눌러 둠 > 받는 쪽이 생해 줘야 함 > 주는 쪽이 극함.
 * 축 1(마음)은 이것뿐. 일지 합충은 넣지 않는다(09-25 사장님 「일지가 원하는 파트너의 모습 · 식상이 보여지는 언행인데 갑자기 합충을 계산에 넣으면 별론데?」).
 * 축 2(격, 09-25 사장님 「계절이 아니라 차라리 — 내가 일지 편인이잖아 상대의 격을 보는 것으로」): 내가 바라는 사람(일지 본기 십신)이 상대의 격(월령 격 — 건록 = 비견 · 양인 = 겁재)과 같은가. 같은 십신 1 · 같은 무리(비겁 · 식상 · 재 · 관 · 인) ½ · 다름 0. 성패는 보지 않는다.
 * 합치기: 마음 85 : 격 15. 축은 둘에서 멈춘다. 점수표 · 비율은 내 추론 — 사장님 검수 대기. 한 곳에서만 고친다.
 * 상위 %: 무작위 명식 2만 쌍으로 뽑은 표(위표) — 점수 식을 바꾸면 같은 씨앗으로 2만 쌍을 다시 돌려 위표를 새로 뽑는다.
 * 끌림: 바라는 게 더 채워지는 쪽이 더 끌린다. 문장은 ChaeksaSsomScoreMal(작가 원고). */
(function (global) {
  const E = global.ChaeksaEngine, S = global.ChaeksaSsom;
  const 점 = { 같은글자: 96, 같은기운: 88, 채워줌: 80, 눌러둠: 64, 채워줘야: 58, 엇갈림: 46 };
  const 비율 = { 마음: 0.85, 격: 15 };
  const 위표 = [[97,0.02],[93,0.06],[90,0.1],[89,0.41],[86,1.05],[85,1.23],[83,1.43],[82,3.49],[80,3.6],[79,5.28],[78,6.33],[77,6.41],[76,7.78],[75,11.48],[73,12.46],[72,14.39],[71,17.08],[70,18.06],[69,20.69],[68,28.05],[67,28.12],[66,29.98],[65,36.45],[64,37.89],[63,38.11],[62,42.25],[61,49.43],[60,51.81],[59,58.28],[58,59.01],[57,63.51],[56,64.55],[55,64.74],[54,73.89],[53,74.48],[52,80.78],[51,82.14],[50,82.22],[49,84.83],[48,86.11],[47,92.18],[44,96.84],[43,97.36],[39,100]];   // [[점수, 그 점수 이상 비율 %]] 높은 점수부터 — 09-25 무작위 명식 2만 쌍(1985~2002년생, 씨앗 12345)
  const 무리 = { 비견: 0, 겁재: 0, 식신: 1, 상관: 1, 편재: 2, 정재: 2, 편관: 3, 정관: 3, 편인: 4, 정인: 4 }, 격십신 = { 건록: '비견', 양인: '겁재' };
  function 격맞음(바라는R, 상대R) {
    let 격 = null; try { 격 = global.ChaeksaTypecard.gyeok(상대R).name; } catch (e) { return { 키: '다름', 값: 0, 격: null }; }
    격 = 격십신[격] || 격; const 바람 = S.일지십신(바라는R);
    if (격 === 바람) return { 키: '같음', 값: 1, 격 };
    if (무리[격] != null && 무리[격] === 무리[바람]) return { 키: '같은무리', 값: 0.5, 격 };
    return { 키: '다름', 값: 0, 격 };
  }
  const 본기 = (R) => { const h = (E.HIDDEN[R.pillars.day.branch] || [])[0]; return typeof h === 'number' ? h : h[0]; };
  const 주는글자 = (R) => { const 언 = (S.언행(R) || [])[0]; return 언 ? E.STEMS.indexOf(언.글자) : R.pillars.day.stem; };
  function 관계(받, 주) {   // 받 = 받는 쪽 일지 본기, 주 = 주는 쪽 글자
    if (받 === 주) return '같은글자';
    const a = E.STEM_ELEM[주], b = E.STEM_ELEM[받];
    if (a === b) return '같은기운';
    if ((a + 1) % 5 === b) return '채워줌';
    if ((b + 1) % 5 === a) return '채워줘야';
    if ((b + 2) % 5 === a) return '눌러둠';
    return '엇갈림';
  }
  function 방향(받는R, 주는R) { const k = 관계(본기(받는R), 주는글자(주는R)); return { 관계: k, 점: 점[k] }; }
  function 재기(나R, 그R) {
    const 나쪽 = 방향(나R, 그R), 그쪽 = 방향(그R, 나R);
    const 나격 = 격맞음(나R, 그R), 그격 = 격맞음(그R, 나R);
    const 마음 = (나쪽.점 + 그쪽.점) / 2;
    const 점수 = Math.max(0, Math.min(100, Math.round(마음 * 비율.마음 + (나격.값 + 그격.값) / 2 * 비율.격)));
    const 끌림 = 나쪽.점 === 그쪽.점 ? '비슷' : 나쪽.점 > 그쪽.점 ? '당신' : '그 사람';
    return { 점수, 나쪽, 그쪽, 나격, 그격, 끌림, 위: 위(점수) };
  }
  function 위(점수) { const t = global.ChaeksaSsomScoreRank || 위표; if (!t) return null; for (const [p, pc] of t) if (점수 >= p) return pc; return 100; }
  const esc = (t) => String(t).replace(/[&<>"]/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[c]);
  function 카드(나R, 그R) {
    const r = 재기(나R, 그R), 말 = global.ChaeksaSsomScoreMal || {}, 한 = (k) => (말.관계 && 말.관계[k]) || '';
    const 끌 = (말.끌림 || {})[r.끌림] || '';
    const 줄 = (누, d) => 한(d.관계) ? '<p><b>' + 누 + '</b> ' + esc(한(d.관계)) + '</p>' : '';
    const 계 = (누, c) => 말.격 && 말.격[c.키] ? '<p><b>' + 누 + '</b> ' + esc(말.격[c.키]) + '</p>' : '';
    return '<div class="card ss-score"><p class="ss-score-n"><b>' + r.점수 + '</b>점' + (r.위 != null ? ' · 상위 ' + (r.위 < 1 ? r.위.toFixed(1) : Math.round(r.위)) + '%' : '') + '</p>'
      + (끌 ? '<p class="ss-lead">' + esc(끌) + '</p>' : '')
      + 줄('당신이 바라는 것 →', r.나쪽) + 줄('그 사람이 바라는 것 →', r.그쪽)
      + (r.나격.키 === r.그격.키 ? 계('둘 다 →', r.나격) : 계('그 사람은 →', r.나격) + 계('당신은 →', r.그격))
      + '</div>';
  }
  global.ChaeksaSsomScore = { 재기, 카드, 관계, 점 };
})(window);
