/* 연애궁합 3초 결과 — 점수 · 누가 더 끌리나(09-25 사장님 「대중이 원하는 건 순위 나열」 · 「3초 결과」 · 「일단 무료로 다 풀고」).
 * 한 축만 잰다(삼체가 되지 않게): 받는 쪽이 바라는 것(일지 본기) × 주는 쪽이 대하는 법(앞선 식상 글자, 없으면 일간 그대로).
 * 두 글자의 오행 관계로 한 방향을 매긴다. 같은 글자 > 같은 기운 > 주는 쪽이 생해 줌 > 받는 쪽이 눌러 둠 > 받는 쪽이 생해 줘야 함 > 주는 쪽이 극함.
 * 두 사람 일지(같은 배우자궁)가 육합이면 더하고 충이면 뺀다 — 여기까지가 축 1(마음).
 * 축 2(계절, 09-25 사장님 「축을 3개 가져가면 삼체문제가 되니까 2개까지만」): 궁통보감 — 내가 태어난 계절에서 먼저 찾는 글자를 상대가 천간에 가졌나(있음 1 · 돕는 글자만 ½ · 없음 0).
 * 합치기: 마음 85 : 계절 15. 축은 둘에서 멈춘다. 점수표 · 비율은 내 추론 — 사장님 검수 대기. 한 곳에서만 고친다.
 * 상위 %: 무작위 명식 2만 쌍으로 뽑은 표(위표) — 점수 식을 바꾸면 같은 씨앗으로 2만 쌍을 다시 돌려 위표를 새로 뽑는다.
 * 끌림: 바라는 게 더 채워지는 쪽이 더 끌린다. 문장은 ChaeksaSsomScoreMal(작가 원고). */
(function (global) {
  const E = global.ChaeksaEngine, S = global.ChaeksaSsom;
  const 점 = { 같은글자: 96, 같은기운: 88, 채워줌: 80, 눌러둠: 64, 채워줘야: 58, 엇갈림: 46 };
  const 일지더 = { 육합: 6, 충: -8 }, 비율 = { 마음: 0.85, 계절: 15 };
  const 위표 = [[100,0.02],[97,0.14],[95,0.22],[94,0.25],[93,0.73],[92,0.75],[91,0.94],[90,1.57],[89,2.14],[88,2.31],[87,2.52],[86,4.6],[85,4.9],[84,5.32],[83,7.06],[82,8.76],[81,9.13],[80,9.86],[79,14.24],[78,14.65],[77,16.08],[76,20.38],[75,22.18],[74,23.41],[73,25.8],[72,31.96],[71,32.9],[70,35.61],[69,40.45],[68,44.1],[67,45.2],[66,49.48],[65,53.37],[64,55.96],[63,57.83],[62,62.22],[61,67.33],[60,67.66],[59,72.16],[58,75.14],[57,78.44],[56,80.19],[55,81.73],[54,85.28],[53,86.37],[52,89.68],[51,91.59],[50,92.48],[49,93.16],[48,94.86],[47,97.1],[46,97.22],[45,97.47],[44,98.32],[43,99.06],[41,99.27],[40,99.37],[39,99.91],[37,99.95],[36,99.98],[32,100]];   // [[점수, 그 점수 이상 비율 %]] 높은 점수부터 — 09-25 무작위 명식 2만 쌍(1985~2002년생, 씨앗 12345)
  function 계절(찾는R, 주는R) {
    let 조 = null; try { 조 = global.ChaeksaClassic.gungtong(찾는R); } catch (e) { return { 키: '없음', 값: 0 }; }
    const 글 = ['year', 'month', 'day', 'hour'].filter(k => 주는R.pillars[k]).map(k => E.STEMS[주는R.pillars[k].stem]);
    if (글.indexOf(조.need) >= 0) return { 키: '있음', 값: 1 };
    if ((Array.isArray(조.aux) ? 조.aux : String(조.aux || '').split('')).some(ch => 글.indexOf(ch) >= 0)) return { 키: '돕는글자', 값: 0.5 };
    return { 키: '없음', 값: 0 };
  }
  const 본기 = (R) => { const h = (E.HIDDEN[R.pillars.day.branch] || [])[0]; return typeof h === 'number' ? h : h[0]; };
  const 주는글자 = (R) => { const 언 = (S.언행(R) || [])[0]; return 언 ? E.STEMS.indexOf(언.글자) : R.pillars.day.stem; };
  function 관계(받, 주) {   // 받 = 받는 쪽 일지 본기, 주 = 주는 쪽 글자
    if (받 === 주) return '같은글자';
    const a = E.STEM_ELEM[주], b = E.STEM_ELEM[받];
    if (a === b) return '같은기운';
    if ((a + 1) % 5 === b) return '채워줌';
    if ((b + 1) % 5 === a) return '채워줘야';
    if ((b + 2) % 5 === a) return '눌러둠';
    return '엇갈림';
  }
  function 방향(받는R, 주는R) { const k = 관계(본기(받는R), 주는글자(주는R)); return { 관계: k, 점: 점[k] }; }
  function 재기(나R, 그R) {
    const 나쪽 = 방향(나R, 그R), 그쪽 = 방향(그R, 나R);
    const 지 = S.지관계(나R.pillars.day.branch, 그R.pillars.day.branch), 더 = 일지더[지] || 0;
    const 나계절 = 계절(나R, 그R), 그계절 = 계절(그R, 나R);
    const 마음 = (나쪽.점 + 그쪽.점) / 2 + 더;
    const 점수 = Math.max(0, Math.min(100, Math.round(마음 * 비율.마음 + (나계절.값 + 그계절.값) / 2 * 비율.계절)));
    const 끌림 = 나쪽.점 === 그쪽.점 ? '비슷' : 나쪽.점 > 그쪽.점 ? '당신' : '그 사람';
    return { 점수, 나쪽, 그쪽, 나계절, 그계절, 일지: 지 === '반합' ? null : 지, 끌림, 위: 위(점수) };
  }
  function 위(점수) { const t = global.ChaeksaSsomScoreRank || 위표; if (!t) return null; for (const [p, pc] of t) if (점수 >= p) return pc; return 100; }
  const esc = (t) => String(t).replace(/[&<>"]/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[c]);
  function 카드(나R, 그R) {
    const r = 재기(나R, 그R), 말 = global.ChaeksaSsomScoreMal || {}, 한 = (k) => (말.관계 && 말.관계[k]) || '';
    const 끌 = (말.끌림 || {})[r.끌림] || '';
    const 줄 = (누, d) => 한(d.관계) ? '<p><b>' + 누 + '</b> ' + esc(한(d.관계)) + '</p>' : '';
    const 계 = (누, c) => 말.계절 && 말.계절[c.키] ? '<p><b>' + 누 + '</b> ' + esc(말.계절[c.키]) + '</p>' : '';
    return '<div class="card ss-score"><p class="ss-score-n"><b>' + r.점수 + '</b>점' + (r.위 != null ? ' · 상위 ' + (r.위 < 1 ? r.위.toFixed(1) : Math.round(r.위)) + '%' : '') + '</p>'
      + (끌 ? '<p class="ss-lead">' + esc(끌) + '</p>' : '')
      + 줄('당신이 바라는 것 →', r.나쪽) + 줄('그 사람이 바라는 것 →', r.그쪽)
      + 계('당신의 계절 →', r.나계절) + 계('그 사람의 계절 →', r.그계절)
      + (r.일지 && 말.일지 && 말.일지[r.일지] ? '<p>' + esc(말.일지[r.일지]) + '</p>' : '')
      + '</div>';
  }
  global.ChaeksaSsomScore = { 재기, 카드, 관계, 점 };
})(window);
