# -*- coding: utf-8 -*-
"""블로그판 「눈여겨볼 것」의 숫자를 자료에서 도로 뽑아 대조한다.

**내가 쓴 글을 내가 검수하는 문제**(2026-09-10 사장님 지적)를 줄이려고 만들었다.
줄이는 것이지 없애는 게 아니다 — 여기서 잡히는 건 **셀 수 있는 주장**뿐이다.
「낮이 확실히 밀립니다」 같은 판단은 이 파일이 못 잡는다.

원칙 하나: **기대값을 손으로 적지 않는다.** 전부 _taekil.json 에서 계산해서,
글에 적힌 숫자와 맞대본다. 기대값을 적어 넣으면 내가 쓴 걸 내가 베끼는 셈이라
검사가 아니라 메아리가 된다.
"""
import io
import json
import re
import sys

try:
    sys.stdout.reconfigure(encoding='utf-8')
except Exception:
    pass

시진 = ['자', '축', '인', '묘', '진', '사', '오', '미', '신', '유', '술', '해']
DATA = json.load(io.open('.taekil/_taekil.json', encoding='utf-8'))


def 창(i, shift):
    s = (23 + 2 * i) % 24 * 60 + shift
    e = (s + 120) % 1440
    return '%02d:%02d~%02d:%02d' % (s // 60 % 24, s % 60, e // 60 % 24, e % 60)


def 칸들(키):
    """(순위, 일, 요일, 시진index, 점수) 목록."""
    v = DATA[키]
    out = []
    for r in v['d']:
        for i in range(12):
            out.append((r[15 + i], r[0], r[1], i, r[3 + i]))
    return sorted(out), v


def 평일낮(키):
    """시계 09:00~17:00 안에 드는 슬롯은 i=5,6,7,8 뿐이다(각 슬롯 대표시각 2i:30)."""
    rows, v = 칸들(키)
    c = [x for x in rows if x[3] in (5, 6, 7, 8) and x[2] not in ('토', '일')]
    return c[0] if c else None


def 본문(m):
    s = io.open('marketing/붙여넣기-%s월출산택일.html' % m, encoding='utf-8').read()
    s = s.replace('\r\n', '\n')
    a = s.index('이달에서 눈여겨볼 것')
    b = s.index('<h3>시계 시각을 꼭 확인하세요')
    j = s.index('이달의 절기')
    return s[j:a] + s[a:b]


기 = []


def 재본다(이름, 글에, 자료에):
    기.append((이름, 글에, 자료에, str(글에) == str(자료에)))


월키 = {'3': '2027-3', '4': '2027-4', '5': '2027-5',
        '6': '2027-6', '7': '2027-7', '8': '2027-8'}

for m, 키 in sorted(월키.items(), key=lambda kv: int(kv[0])):
    rows, v = 칸들(키)
    t = 본문(m)
    shift = v['shift']
    일요일 = {r[0]: r[1] for r in v['d']}

    # ── 1. 글에 적힌 「N위」 주장을 전부 뽑아 대조 ──
    # 「25일 미시(13:33~15:33) … 89점, 전체 14위」 같은 문장.
    for 일, 진, 점, 순 in re.findall(
            r'(\d+)일[^<]{0,12}<b>[^<]*</b>?[^<]{0,40}?(?:</b>)?'
            r'.{0,80}?(\d+)점, 전체 (\d+)위', t, re.S) or []:
        pass  # 아래 개별 검사로 대신한다 — 정규식으로 문장을 파싱하면 파서가 또 내 것이다

    # ── 2. 셀 수 있는 것들 ──
    # 2-1 백점 칸. 「100점은 둘입니다」 / 「100점 네 자리 중」 두 꼴을 받는다.
    # 주장이 없는 달은 건너뛴다 — 없는 주장을 통과시키면 검사가 아니라 장식이다.
    백 = [x for x in rows if x[4] == 100]
    수말 = {'하나': 1, '둘': 2, '셋': 3, '넷': 4, '네': 4, '다섯': 5,
            '여섯': 6, '일곱': 7, '여덟': 8, '아홉': 9, '열': 10}
    글백 = re.search(r'100점(?:은|이)?\s*(하나|둘|셋|넷|다섯)', t) \
        or re.search(r'100점 (하나|둘|셋|넷|네|다섯) ?자리', t)
    if 글백:
        재본다('%s월 100점 칸 수' % m, 수말[글백.group(1)], len(백))

    # 2-2 평일 낮 최고 — 글에 적힌 「전체 N위」 중 평일낮 문맥의 것
    p = 평일낮(키)
    문 = re.search(r'평일 낮[^<]*(?:</b>)?[^<]*<b>(\d+)일\((.)\) (\S)시</b>'
                   r'\((\d\d:\d\d~\d\d:\d\d)\)', t)
    if not 문:
        문 = re.search(r'<b>(\d+)일\((.)\) (\S)시</b>\((\d\d:\d\d~\d\d:\d\d)\)', t)
    if 문:
        재본다('%s월 평일낮 최고 — 날' % m, int(문.group(1)), p[1])
        재본다('%s월 평일낮 최고 — 요일' % m, 문.group(2), p[2])
        재본다('%s월 평일낮 최고 — 시진' % m, 문.group(3), 시진[p[3]])
        재본다('%s월 평일낮 최고 — 시각창' % m, 문.group(4), 창(p[3], shift))
    문2 = re.search(r'(\d+)점, 전체 (\d+)위', t)
    if 문2:
        재본다('%s월 평일낮 최고 — 점수' % m, int(문2.group(1)), p[4])
        재본다('%s월 평일낮 최고 — 순위' % m, int(문2.group(2)), p[0])

    # 2-3 「상위 20위 중 N이 X시」
    top20 = rows[:20]
    for 수, 진 in re.findall(r'<b>(하나|둘|셋|넷|다섯|여섯|일곱|여덟|아홉|열|열하나|열둘)'
                             r'(?:이|가)?\s*(\S)시</b>', t):
        한글수 = {'하나': 1, '둘': 2, '셋': 3, '넷': 4, '다섯': 5, '여섯': 6,
                  '일곱': 7, '여덟': 8, '아홉': 9, '열': 10, '열하나': 11, '열둘': 12}
        실 = sum(1 for x in top20 if 시진[x[3]] == 진)
        재본다('%s월 상위20 중 %s시' % (m, 진), 한글수[수], 실)

    # 2-4 「열두 칸 중 가장 낮은 칸이 N점」
    for 일, 최저 in re.findall(r'(\d+)일[^<]{0,30}열두 칸 최저가 (\d+)점', t):
        실 = min(r[3:15] for r in v['d'] if r[0] == int(일))
        재본다('%s월 %s일 열두 칸 최저' % (m, 일), int(최저), min(실))
    문3 = re.search(r'열두 시진 중 가장 낮은 칸이 (\d+)점', t)
    if 문3:
        봉 = re.search(r'<b>(\d+)일이 이달의 봉우리', t)
        row = [r for r in v['d'] if r[0] == int(봉.group(1))][0]
        재본다('%s월 봉우리 날 최저점' % m, int(문3.group(1)), min(row[3:15]))

    # 2-5 「상위 20위 안에 N자리가 이 하루에」
    문4 = re.search(r'상위 20위 안에 <b>(\S+) ?자리</b>가 이 하루', t)
    if 문4:
        한글수 = {'하나': 1, '둘': 2, '셋': 3, '넷': 4, '다섯': 5, '여섯': 6,
                  '일곱': 7, '여덟': 8, '아홉': 9, '열': 10}
        봉 = int(re.search(r'<b>(\d+)일이 이달의 봉우리', t).group(1))
        재본다('%s월 봉우리 날의 상위20 칸' % m,
               한글수[문4.group(1).replace(' ', '')],
               sum(1 for x in top20 if x[1] == 봉))

    # 2-6 전체 1위 — 「1위는 N일(요일) X시」
    문5 = re.search(r'1위는 (\d+)일\((.)\) (\S)시', t)
    if 문5:
        재본다('%s월 전체 1위 — 날' % m, int(문5.group(1)), rows[0][1])
        재본다('%s월 전체 1위 — 요일' % m, 문5.group(2), rows[0][2])
        재본다('%s월 전체 1위 — 시진' % m, 문5.group(3), 시진[rows[0][3]])

    # 2-7 시계 어긋남
    문6 = re.search(r'시계와 사주가 <b>(\d+)분</b> 어긋납니다', t)
    if 문6:
        재본다('%s월 보정폭' % m, int(문6.group(1)), shift)

    # 2-8 「지난 아홉 달」류 — 앞선 달들의 평일낮 순위 집합
    문7 = re.search(r'지난 (\S+) 달 자료에서 평일 낮 최고는 ([\d위·]+)였습니다', t)
    if 문7:
        차례 = ['2026-9', '2026-10', '2026-11', '2026-12', '2027-1', '2027-2',
                '2027-3', '2027-4', '2027-5', '2027-6', '2027-7', '2027-8']
        앞 = 차례[:차례.index(키)]
        실순 = sorted({평일낮(k)[0] for k in 앞})
        한글수 = {'한': 1, '두': 2, '석': 3, '넉': 4, '다섯': 5, '여섯': 6,
                  '일곱': 7, '여덟': 8, '아홉': 9, '열': 10, '열한': 11}
        재본다('%s월 「지난 N 달」의 N' % m, 한글수.get(문7.group(1), 문7.group(1)), len(앞))
        재본다('%s월 「지난 N 달」 순위 목록' % m,
               [int(x) for x in re.findall(r'(\d+)위', 문7.group(2))], 실순)

    # 2-9 「앞의 석 달은 1위·3위·4위」
    문8 = re.search(r'앞의 (\S+) 달은 ([\d위·]+)였습니다', t)
    if 문8:
        차례 = ['2027-3', '2027-4', '2027-5', '2027-6', '2027-7', '2027-8']
        한글수 = {'한': 1, '두': 2, '석': 3, '넉': 4, '다섯': 5}
        n = 한글수[문8.group(1)]
        i = 차례.index(키)
        앞 = 차례[max(0, i - n):i]
        재본다('%s월 「앞의 N 달」 순위' % m,
               [int(x) for x in re.findall(r'(\d+)위', 문8.group(2))],
               [평일낮(k)[0] for k in 앞])

    # 2-10 「하루 안에서 끝과 끝」 — N점 M위 / N점 M위
    for 진, 창문, 점, 순 in re.findall(
            r'(\S)시\((\d\d:\d\d~\d\d:\d\d)\)(?:가|는) (\d+)점 (\d+)위', t):
        일문 = re.search(r'<b>(\d+)일은 하루 안에서', t)
        if not 일문:
            continue
        일 = int(일문.group(1))
        i = 시진.index(진)
        row = [r for r in v['d'] if r[0] == 일][0]
        재본다('%s월 %d일 %s시 점수' % (m, 일, 진), int(점), row[3 + i])
        재본다('%s월 %d일 %s시 순위' % (m, 일, 진), int(순), row[15 + i])
        재본다('%s월 %d일 %s시 창' % (m, 일, 진), 창문, 창(i, shift))

    # 2-11 본문에 적힌 모든 「(HH:MM~HH:MM)」 창이 그 시진의 창과 맞는가
    for 진, 창문 in re.findall(r'(\S)시</b>?\((\d\d:\d\d~\d\d:\d\d)\)', t):
        if 진 in 시진:
            재본다('%s월 %s시 창 표기' % (m, 진), 창문, 창(시진.index(진), shift))

폭 = max(len(x[0]) for x in 기)
틀림 = 0
for 이름, 글에, 자료에, ok in 기:
    if not ok:
        틀림 += 1
    print('%s  %-*s  글 %-22s 자료 %s'
          % ('O ' if ok else 'X!', 폭, 이름, str(글에), str(자료에)))
print()
print('%d개 대조 · 어긋남 %d개' % (len(기), 틀림))
sys.exit(1 if 틀림 else 0)
